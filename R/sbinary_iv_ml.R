#' @title Maximum Likelihood Estimation for Spatial Binary Probit Models with a Continuous Endogenous Regressor
#'
#' @description
#' Estimates a spatial autoregressive probit model with a continuous endogenous
#' regressor by maximum likelihood. The probability contribution of the binary
#' outcome is evaluated either by the Mendell--Elston (ME) approximation or by
#' recursive importance sampling (RIS).
#'
#' The latent-variable model is
#'
#' \deqn{
#' y^* = X\beta + WX\gamma + \lambda W y^* + \varepsilon,
#' }
#'
#' where \eqn{y = 1} if \eqn{y^* > 0} and zero otherwise. One continuous
#' regressor in the structural equation is allowed to be endogenous. Let
#' \eqn{x_e} denote this regressor. Its reduced-form equation is
#'
#' \deqn{
#' x_e = Z\pi + v,
#' }
#'
#' where \eqn{Z} contains the exogenous structural regressors and the excluded
#' instruments supplied by the user. Endogeneity is introduced through the
#' correlation between the structural disturbance and the reduced-form
#' disturbance:
#'
#' \deqn{
#' \mathrm{Corr}(\varepsilon, v) = \rho.
#' }
#'
#' Conditional on \eqn{v}, the spatial binary model has mean
#'
#' \deqn{
#' \mu =
#' (I - \lambda W)^{-1}
#' \left(
#' X\beta + WX\gamma + \frac{\rho}{\sigma_v}v
#' \right),
#' }
#'
#' and covariance matrix
#'
#' \deqn{
#' \Omega =
#' (1-\rho^2)
#' (I-\lambda W)^{-1}
#' (I-\lambda W)^{-T}.
#' }
#'
#' The joint likelihood combines the Gaussian likelihood of the reduced-form
#' equation for \eqn{x_e} with the multivariate normal probability associated
#' with the binary outcome.
#'
#' @name sbinary_iv_ml
#'
#' @param formula A symbolic description of the model of the form
#'   \code{y ~ x | wx | instruments}. The first right-hand side contains the
#'   structural regressors, including the continuous endogenous regressor. The
#'   second right-hand side contains variables whose spatial lags \eqn{WX}
#'   enter the structural equation. The third right-hand side contains the
#'   excluded instruments for the endogenous regressor. Use \code{| 0 |} in
#'   the second part when no spatially lagged regressors are included.
#'
#' @param data A \code{data.frame} containing the variables in the model.
#'
#' @param subset An optional vector specifying a subset of observations to be
#'   used in the estimation.
#'
#' @param na.action A function indicating what should happen when the data
#'   contain \code{NA}s.
#'
#' @param listw A spatial weights object of class \code{listw}, \code{matrix},
#'   or \code{Matrix}.
#'
#' @param endog Character string naming the continuous endogenous regressor.
#'   Only one continuous endogenous regressor is currently supported. The
#'   variable must enter directly in the first part of \code{formula} and
#'   cannot simultaneously appear in the \code{WX} part.
#'
#' @param method Character string indicating how the multivariate normal
#'   probability is evaluated. \code{"ME"} uses the Mendell--Elston
#'   approximation and \code{"RIS"} uses recursive importance sampling.
#'
#' @param varcov Character string indicating the matrix representation used in
#'   the probability calculations. \code{"invsigma"} uses the precision matrix,
#'   whereas \code{"sigma"} uses the covariance matrix. This argument refers to
#'   the Cholesky representation used internally and not to the estimator of
#'   the parameter variance-covariance matrix.
#'
#' @param ordering Character string specifying the ordering used in the
#'   multivariate normal probability evaluation. \code{"N"} uses the natural
#'   ordering and \code{"M"} uses an ordering based on marginal truncation
#'   probabilities. RIS currently supports only \code{"M"}. For ME with
#'   \code{varcov = "invsigma"} and \code{ordering = "M"}, an AMD permutation
#'   is additionally used to reduce fill-in in the sparse Cholesky
#'   factorization.
#'
#' @param R Integer. Number of antithetic simulation draws used when
#'   \code{method = "RIS"}. The default is \code{50}.
#'
#' @param seed Integer. Random-number seed used to generate the common
#'   antithetic draws for RIS. The global random-number state is restored after
#'   the draws are generated.
#'
#' @param start Optional vector of starting values on the structural parameter
#'   scale. Values must be supplied in the order
#'   \eqn{(\beta,\gamma,\lambda,\pi,\sigma_v,\rho)}, according to the columns
#'   generated by the model matrices. If \code{NULL}, starting values are
#'   constructed internally from a linear first-stage regression, a standard
#'   probit model, and a simple initial value for the spatial parameter.
#'
#' @param lambda.margin Numeric. Small positive margin used to keep the
#'   optimization interval for \eqn{\lambda} strictly inside the
#'   eigenvalue-based admissible parameter space.
#'
#' @param maxit Integer. Maximum number of iterations used by the
#'   \code{L-BFGS-B} optimizer.
#'
#' @param factr Numeric. Convergence control parameter passed to
#'   \code{optim(..., method = "L-BFGS-B")}.
#'
#' @param pgtol Numeric. Projected-gradient tolerance passed to the
#'   \code{L-BFGS-B} optimizer.
#'
#' @param hessian Logical. If \code{TRUE}, the observed Hessian is computed at
#'   the optimum using the final ordering held fixed. The resulting matrix is
#'   used by \code{vcov()} and \code{summary()} when
#'   \code{vce = "hessian"}, and is also required by the operational sandwich
#'   covariance estimator.
#'
#' @param print.init Logical. If \code{TRUE}, the starting values are printed
#'   both in optimizer coordinates and on the structural parameter scale.
#'
#' @param verbose Logical. If \code{TRUE}, information on the estimator,
#'   optimization convergence, log-likelihood, and Hessian diagnostics is
#'   printed.
#' 
#' @param x,object A fitted object of class \code{"binivml"}.
#' 
#' @param vce Covariance estimator. \code{"hessian"} (default) returns the
#'   inverse fixed-order observed Hessian. \code{"sandwich"} computes the
#'   operational model-based sandwich.
#'   
#' @param R Number of inner parametric simulations for the sandwich estimator.
#' 
#' @param seed Integer seed for the sandwich simulations.
#' 
#' @param digits Integer. The number of significant digits used when printing
#'   the model summary. 
#' 
#' @param ... Reserved for compatibility.
#'
#' @details
#'
#' Let
#'
#' \deqn{
#' A(\lambda) = I - \lambda W
#' }
#'
#' and let the reduced-form residual of the endogenous regressor be
#'
#' \deqn{
#' v = x_e - Z\pi.
#' }
#'
#' Under joint normality of the structural and reduced-form disturbances, the
#' structural disturbance can be written conditionally on \eqn{v} as
#'
#' \deqn{
#' \varepsilon
#' =
#' \frac{\rho}{\sigma_v}v
#' +
#' \sqrt{1-\rho^2}\eta,
#' \qquad
#' \eta \sim N(0,I).
#' }
#'
#' Hence, conditional on the endogenous regressor,
#'
#' \deqn{
#' y^*
#' =
#' A(\lambda)^{-1}
#' \left(
#' X\beta + WX\gamma + \frac{\rho}{\sigma_v}v
#' \right)
#' +
#' \sqrt{1-\rho^2}
#' A(\lambda)^{-1}\eta.
#' }
#'
#' The binary likelihood contribution therefore requires evaluation of an
#' \eqn{n}-dimensional normal probability. When \code{method = "ME"}, this
#' probability is approximated using the Mendell--Elston recursive
#' approximation. When \code{method = "RIS"}, it is evaluated using a
#' GHK-type recursive importance sampler with common antithetic draws.
#'
#' Two algebraically equivalent matrix representations are available.
#' With \code{varcov = "sigma"}, the recursion uses
#'
#' \deqn{
#' \Omega =
#' (1-\rho^2)A(\lambda)^{-1}A(\lambda)^{-T}.
#' }
#'
#' With \code{varcov = "invsigma"}, it uses the corresponding precision
#' matrix
#'
#' \deqn{
#' \Omega^{-1}
#' =
#' \frac{A(\lambda)'A(\lambda)}{1-\rho^2}.
#' }
#'
#' The estimator maximizes the joint log-likelihood
#'
#' \deqn{
#' \ell(\theta)
#' =
#' \ell_x(\pi,\sigma_v)
#' +
#' \log P(y \mid x_e,X,Z,W;\theta),
#' }
#'
#' where
#'
#' \deqn{
#' \theta =
#' (\beta,\gamma,\lambda,\pi,\sigma_v,\rho).
#' }
#'
#' Internally, \eqn{\sigma_v} and \eqn{\rho} are parameterized as
#' \eqn{\log(\sigma_v)} and \eqn{\mathrm{atanh}(\rho)} so that
#' \eqn{\sigma_v>0} and \eqn{|\rho|<1}. The spatial autoregressive parameter
#' \eqn{\lambda} is optimized directly subject to eigenvalue-based bounds.
#'
#' Analytic gradients are used for the likelihood optimization. If the Hessian
#' is requested, it is evaluated after optimization while keeping the final
#' probability ordering fixed.
#'
#' Standard errors can subsequently be obtained with \code{vcov()} or
#' \code{summary()}. The default \code{vce = "hessian"} uses the inverse
#' observed Hessian. For ME estimators, \code{vce = "sandwich"} provides an
#' operational model-based sandwich covariance matrix based on parametric
#' simulations of the joint model. The sandwich estimator is currently not
#' available for RIS.
#'
#' @return
#' An object of class \code{"binivml"}, containing the estimated coefficients
#' and the information required by the associated \code{coef}, \code{vcov},
#' \code{logLik}, \code{print}, and \code{summary} methods. The main elements
#' include:
#'
#' \item{coefficients}{Estimated parameters on the structural scale.}
#' \item{vcov_hessian}{Variance-covariance matrix obtained from the inverse
#' observed Hessian, when available.}
#' \item{se_hessian}{Hessian-based standard errors, when available.}
#' \item{call}{The matched function call.}
#' \item{callF}{The full matched call.}
#' \item{formula}{The model formula.}
#' \item{mf}{The model frame used in estimation.}
#' \item{data}{The original data supplied to the function.}
#' \item{y}{The binary dependent variable.}
#' \item{X}{The structural regressor matrix, including spatially lagged
#' regressors when requested.}
#' \item{Z}{The first-stage instrument matrix, formed from the exogenous
#' structural regressors and the excluded instruments.}
#' \item{excluded}{The matrix containing the excluded instruments.}
#' \item{xend}{The continuous endogenous regressor.}
#' \item{endog}{The name of the endogenous regressor.}
#' \item{listw}{The spatial weights matrix used in estimation.}
#' \item{method}{The probability evaluator used, either \code{"ME"} or
#' \code{"RIS"}.}
#' \item{varcov}{The covariance or precision representation used in the
#' probability recursion.}
#' \item{ordering}{The ordering rule used.}
#' \item{logLik}{The maximized joint log-likelihood.}
#' \item{opt}{A list containing optimization results, analytic scores,
#' ordering information, Hessian diagnostics, and timing information.}
#' \item{bounds}{The parameter bounds used by the optimizer.}
#'
#' @author Mauricio Sarrias and Gianfranco Piras
#' @examples
#' \donttest{
#' ## ---------------------------------------------------------
#' ## Data-generating process
#' ## ---------------------------------------------------------
#'
#' set.seed(12345)
#'
#' ## Spatial weights matrix from a regular lattice
#' nr <- 10
#' nc <- 10
#' n  <- nr * nc
#'
#' nb <- spdep::cell2nb(
#'   nrow = nr,
#'   ncol = nc,
#'   type = "queen"
#' )
#'
#' lw <- spdep::nb2listw(
#'   nb,
#'   style = "W",
#'   zero.policy = TRUE
#' )
#'
#' W <- spdep::listw2mat(lw)
#'
#' ## Exogenous regressors and excluded instruments
#' x1 <- stats::rnorm(n)
#' x3 <- stats::rnorm(n)
#' z1 <- stats::rnorm(n)
#' z2 <- stats::rnorm(n)
#'
#' ## Spatially lagged regressor
#' Wx1 <- as.numeric(W %*% x1)
#'
#' ## Parameters governing endogeneity
#' sigma_v <- 1
#' rho     <- 0.5
#'
#' zv   <- stats::rnorm(n)
#' zeta <- stats::rnorm(n)
#'
#' ## Reduced-form disturbance
#' v <- sigma_v * zv
#'
#' ## Continuous endogenous regressor
#' x2 <- 0.3 +
#'   0.5 * x1 -
#'   0.3 * x3 +
#'   0.8 * z1 -
#'   0.6 * z2 +
#'   v
#'
#' ## Structural disturbance correlated with v
#' eps <- rho * zv +
#'   sqrt(1 - rho^2) * zeta
#'
#' ## Structural parameters
#' lambda <- 0.6
#'
#' ## Latent spatial binary model with WX
#' rhs <- -0.2 +
#'   0.5 * x1 +
#'   0.8 * x2 -
#'   0.4 * x3 +
#'   0.35 * Wx1 +
#'   eps
#'
#' ystar <- solve(
#'   diag(n) - lambda * W,
#'   rhs
#' )
#'
#' y <- as.numeric(ystar > 0)
#'
#' dat <- data.frame(
#'   y  = y,
#'   x1 = x1,
#'   x2 = x2,
#'   x3 = x3,
#'   z1 = z1,
#'   z2 = z2
#' )
#'
#' ## Model with x2 endogenous, Wx1 in the structural equation,
#' ## and z1 and z2 as excluded instruments.
#' form <- y ~ x1 + x2 + x3 | x1 | z1 + z2
#'
#'
#' ## ---------------------------------------------------------
#' ## Mendell-Elston estimators
#' ## ---------------------------------------------------------
#'
#' ## ME using the covariance matrix and natural ordering
#' me_sigma_n <- sbinary_iv_ml(
#'   form,
#'   data = dat,
#'   listw = lw,
#'   endog = "x2",
#'   method = "ME",
#'   varcov = "sigma",
#'   ordering = "N"
#' )
#'
#' ## Hessian standard errors
#' summary(me_sigma_n)
#'
#' ## Sandwich standard errors
#' summary(
#'   me_sigma_n,
#'   vce = "sandwich",
#'   R = 50,
#'   seed = 123
#' )
#'
#'
#' ## ME using the covariance matrix and marginal ordering
#' me_sigma_m <- sbinary_iv_ml(
#'   form,
#'   data = dat,
#'   listw = lw,
#'   endog = "x2",
#'   method = "ME",
#'   varcov = "sigma",
#'   ordering = "M"
#' )
#'
#' summary(me_sigma_m)
#' summary(
#'   me_sigma_m,
#'   vce = "sandwich",
#'   R = 50,
#'   seed = 123
#' )
#'
#'
#' ## ME using the precision matrix and natural ordering
#' me_invsigma_n <- sbinary_iv_ml(
#'   form,
#'   data = dat,
#'   listw = lw,
#'   endog = "x2",
#'   method = "ME",
#'   varcov = "invsigma",
#'   ordering = "N"
#' )
#'
#' summary(me_invsigma_n)
#' summary(
#'   me_invsigma_n,
#'   vce = "sandwich",
#'   R = 50,
#'   seed = 123
#' )
#'
#'
#' ## ME using the precision matrix and marginal ordering
#' me_invsigma_m <- sbinary_iv_ml(
#'   form,
#'   data = dat,
#'   listw = lw,
#'   endog = "x2",
#'   method = "ME",
#'   varcov = "invsigma",
#'   ordering = "M"
#' )
#'
#' summary(me_invsigma_m)
#' summary(
#'   me_invsigma_m,
#'   vce = "sandwich",
#'   R = 50,
#'   seed = 123
#' )
#'
#'
#' ## ---------------------------------------------------------
#' ## RIS estimators
#' ## ---------------------------------------------------------
#'
#' ## RIS using the covariance matrix and marginal ordering
#' ris_sigma_m <- sbinary_iv_ml(
#'   form,
#'   data = dat,
#'   listw = lw,
#'   endog = "x2",
#'   method = "RIS",
#'   varcov = "sigma",
#'   ordering = "M",
#'   R = 100,
#'   seed = 123
#' )
#'
#' ## Hessian standard errors
#' summary(ris_sigma_m)
#'
#'
#' ## RIS using the precision matrix and marginal ordering
#' ris_invsigma_m <- sbinary_iv_ml(
#'   form,
#'   data = dat,
#'   listw = lw,
#'   endog = "x2",
#'   method = "RIS",
#'   varcov = "invsigma",
#'   ordering = "M",
#'   R = 100,
#'   seed = 123
#' )
#'
#' ## Hessian standard errors
#' summary(ris_invsigma_m)
#'
#'
#' ## ---------------------------------------------------------
#' ## SAR-probit submodel without WX regressors
#' ## ---------------------------------------------------------
#'
#' ## Use 0 in the second part of the formula when no WX
#' ## regressors enter the structural equation.
#' form_sar <- y ~ x1 + x2 + x3 | 0 | z1 + z2
#'
#' sar <- sbinary_iv_ml(
#'   form_sar,
#'   data = dat,
#'   listw = lw,
#'   endog = "x2",
#'   method = "ME",
#'   varcov = "invsigma",
#'   ordering = "M"
#' )
#'
#' summary(sar)
#' summary(
#'   sar,
#'   vce = "sandwich",
#'   R = 50,
#'   seed = 123
#' )
#' }
#' @references Sarrias, M. (2026). Mendell--Elston Approximate Likelihood for Spatial Probit Models with a Continuous Endogenous Regressor.
#' @seealso \code{\link[spldv]{sbinaryGMM}}, \code{\link[spldv]{sbinaryLGMM}}.
#' @keywords models
#' @rawNamespace import(Matrix,  except = c(cov2cor, toeplitz, update)) 
#' @import stats methods Formula
#' @importFrom sphet listw2dgCMatrix
#' @export
sbinary_iv_ml <- function(formula,
                       data,
                       subset,
                       na.action,
                       listw = NULL,
                       endog,
                       method = c("ME", "RIS"),
                       varcov = c("invsigma", "sigma"),
                       ordering = c("M", "N"),
                       R = 50L,
                       seed = 123L,
                       start = NULL,
                       lambda.margin = 1e-6,
                       maxit = 800L,
                       factr = 1e7,
                       pgtol = 1e-6,
                       hessian = TRUE,
                       print.init = FALSE,
                       verbose = TRUE,
                       ...) {

  method <- match.arg(method)
  varcov <- match.arg(varcov)
  ordering <- match.arg(ordering)

  if (missing(endog) || length(endog) != 1L || !is.character(endog) ||
      is.na(endog) || !nzchar(endog)) {
    stop("'endog' must be a single variable name.")
  }
  if (method == "RIS" && ordering != "M") {
    stop("RIS currently supports ordering = 'M' only.")
  }
  if (method == "RIS") {
    if (!is.numeric(R) || length(R) != 1L || !is.finite(R) || R < 1) {
      stop("'R' must be a positive integer.")
    }
    R <- as.integer(R)
    if (!is.numeric(seed) || length(seed) != 1L || !is.finite(seed)) {
      stop("'seed' must be a finite integer.")
    }
    seed <- as.integer(seed)
  }

  # --- Spatial weights matrix ---
  if (inherits(listw, "listw")) {
    W <- sphet::listw2dgCMatrix(listw)
  } else if (inherits(listw, "matrix")) {
    W <- Matrix::Matrix(listw, sparse = TRUE)
  } else if (inherits(listw, "Matrix")) {
    W <- listw
  } else {
    stop("Neighbourhood list or listw format unknown")
  }
  W <- Matrix::drop0(W)

  if (nrow(W) != ncol(W)) stop("W must be square.")

  # --- Model frame setup, following the existing spldv interface ---
  callT <- match.call(expand.dots = TRUE)
  callF <- match.call(expand.dots = FALSE)
  mf <- callT
  m <- match(c("formula", "data", "subset", "na.action"), names(mf), 0L)
  mf <- mf[c(1L, m)]
  f1 <- Formula::Formula(formula)

  if (length(f1)[2L] != 3L) {
    stop(
      "For sbinary_iv_ml(), formula must have three RHS parts: ",
      "y ~ x | wx | instruments. Use '| 0 |' when no WX terms are required."
    )
  }

  mf$formula <- f1
  mf[[1L]] <- as.name("model.frame")
  mf <- eval(mf, parent.frame())

  # --- Response ---
  y <- stats::model.response(mf)
  if (anyNA(y)) stop("NAs in dependent variable")
  if (!all(y %in% c(0, 1, TRUE, FALSE))) {
    stop("All dependent variables must be either 0, 1, TRUE or FALSE")
  }
  if (!is.numeric(y)) y <- as.numeric(y)
  y <- as.numeric(y)

  if (length(unique(y)) < 2L) {
    stop("The dependent variable must contain both outcome values 0 and 1.")
  }

  if (nrow(W) != length(y)) {
    stop("Number of spatial units in W is different to the number of observations.")
  }

  # --- Structural regressors: first RHS ---
  X0 <- stats::model.matrix(f1, data = mf, rhs = 1)
  contrastsX <- attr(X0, "contrasts")
  Xlevels <- .getXlevels(attr(mf, "terms"), mf)

  if (!endog %in% colnames(X0)) {
    stop(
      "The endogenous regressor '", endog,
      "' must enter the first RHS directly and must correspond to one column of model.matrix()."
    )
  }
  if (identical(endog, "(Intercept)")) {
    stop("The intercept cannot be specified as the endogenous regressor.")
  }

  endog_raw <- mf[[endog]]
  if (is.null(endog_raw) || !is.numeric(endog_raw)) {
    stop(
      "In this function, 'endog' must name a numeric variable in 'data' ",
      "that enters the first RHS directly."
    )
  }
  xend <- as.numeric(X0[, endog])

  if (any(!is.finite(xend))) {
    stop("The endogenous regressor contains non-finite values.")
  }
  if (stats::sd(xend) <= sqrt(.Machine$double.eps)) {
    stop("The endogenous regressor must have non-zero sample variation.")
  }

  # --- Spatially lagged regressors: second RHS ---
  x.for.w <- stats::model.matrix(f1, data = mf, rhs = 2)
  contrastsD <- attr(x.for.w, "contrasts")
  name.wx <- setdiff(colnames(x.for.w), "(Intercept)")

  if (endog %in% name.wx) {
    stop(
      "The endogenous regressor cannot also enter the WX part in this implementation."
    )
  }

  if (length(name.wx)) {
    if (!all(name.wx %in% colnames(X0))) {
      warning(
        "Some variables in WX do not appear in the first RHS. ",
        "Check the formula if this is not intended."
      )
    }
    WX <- W %*% x.for.w[, name.wx, drop = FALSE]
    WX <- as.matrix(WX)
    colnames(WX) <- paste0("lag_", name.wx)
    if (anyNA(WX)) stop("NAs in WX variables")
    X <- cbind(X0, WX)
  } else {
    X <- X0
  }

  if (anyNA(X)) stop("NAs in independent variables")
  if (nrow(X) != nrow(W)) {
    stop("Number of spatial units in W is different to the number of observations.")
  }

  # --- Excluded instruments: third RHS ---
  Zex0 <- stats::model.matrix(f1, data = mf, rhs = 3)
  contrastsI <- attr(Zex0, "contrasts")
  excluded.names <- setdiff(colnames(Zex0), "(Intercept)")

  if (!length(excluded.names)) {
    stop("At least one excluded instrument must be supplied in the third RHS.")
  }

  if (any(excluded.names %in% colnames(X))) {
    overlap <- intersect(excluded.names, colnames(X))
    stop(
      "The third RHS is reserved for excluded instruments. These variables ",
      "also appear in the structural equation: ", paste(overlap, collapse = ", ")
    )
  }

  Zexcluded <- Zex0[, excluded.names, drop = FALSE]
  Xexog <- X[, colnames(X) != endog, drop = FALSE]
  Z <- cbind(Xexog, Zexcluded)

  if (anyNA(Z)) stop("NAs in the first-stage instrument matrix.")
  if (anyDuplicated(colnames(Z))) {
    stop("Duplicated column names detected in the first-stage instrument matrix.")
  }

  qrz <- qr(as.matrix(Z))
  if (qrz$rank < ncol(Z)) {
    stop("The first-stage instrument matrix is rank deficient.")
  }
  if (nrow(Z) <= ncol(Z)) {
    stop("The first-stage instrument matrix has too many columns for the sample size.")
  }

  K <- ncol(X)
  L <- ncol(Z)

  # --- Problem constants and parameter bounds ---
  problem <- .sbivml_prepare_problem(W, lambda.margin = lambda.margin)
  bounds <- .sbivml_joint_bounds(problem, X = X, Z = Z)

  # --- Starting values ---
  if (is.null(start)) {
    start.internal <- .sbivml_make_start(
      y = y, X = X, xend = xend, Z = Z,
      bounds = bounds, problem = problem
    )
  } else {
    start.internal <- .sbivml_structural_start_to_internal(
      start = start, X = X, Z = Z, bounds = bounds
    )
  }

  if (print.init) {
    cat("\nStarting values (optimizer coordinates):\n")
    print(start.internal)
    cat("\nStarting values (structural scale):\n")
    print(.sbivml_structural_vector(start.internal, X = X, Z = Z))
  }

  # --- Common RIS draws ---
  draws <- if (method == "RIS") {
    .sbivml_make_ghk_draws(
      n = length(y), R = R, seed = seed, preserve_seed = TRUE
    )
  } else {
    NULL
  }

  engine <- if (method == "ME") {
    if (varcov == "invsigma") "ME_PM" else "ME_VC"
  } else {
    if (varcov == "invsigma") "RIS_PM" else "RIS_VC"
  }

  rule <- if (method == "RIS") {
    "M"
  } else if (ordering == "N") {
    "N"
  } else {
    "M"
  }

  if (verbose) {
    cat(
      "\n", method, " estimation of spatial binary probit with endogenous regressor\n",
      "Cholesky representation: ", varcov,
      " | ordering: ", ordering,
      if (method == "RIS") paste0(" | R: ", R) else "",
      "\n", sep = ""
    )
  }

  fit <- .sbivml_fit_joint(
    engine = engine,
    rule = rule,
    y = y,
    X = X,
    xend = xend,
    Z = Z,
