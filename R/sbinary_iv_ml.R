.sbivml_prepare_problem <- function(W, lambda.margin = 1e-6) {
  if (nrow(W) != ncol(W)) stop("W must be square.")
  sp  <- .sbivml_spatial_parameter_space(W,endpoint_margin = lambda.margin)
  n   <- nrow(W)
  I_n <- Matrix::Diagonal(n)

  list( 
    W = W,
    n = n,
    pm_cache      = list(I = I_n, Wplus = Matrix::drop0(W + Matrix::t(W)), WtW = Matrix::drop0(Matrix::crossprod(W))),
    lambda_margin = lambda.margin,
    lambda_space  = sp
  )
}

