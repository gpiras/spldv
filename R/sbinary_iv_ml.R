.sbivml_parameter_names <- function(X, Z) {
  c(colnames(X), "lambda", paste0("pi_", colnames(Z)), "log_sigma_v", "rho_raw")
}

.sbivml_structural_names <- function(X, Z) {
  c(colnames(X), "lambda", paste0("pi_", colnames(Z)), "sigma_v", "rho")
}

.sbivml_parameter_index <- function(X, Z) {
  K           <- ncol(X)
  L           <- ncol(Z)
  idx_beta    <- seq_len(K)
  idx_lambda  <- K + 1L
  idx_pi      <- idx_lambda + seq_len(L)
  idx_lsigma  <- idx_lambda + L + 1L
  idx_rho_raw <- idx_lsigma + 1L

  list(
    beta        = idx_beta,
    lambda      = idx_lambda,
    pi          = idx_pi,
    log_sigma_v = idx_lsigma,
    rho_raw     = idx_rho_raw,
    p           = idx_rho_raw
  )
}

.sbivml_make_parameter_vector <- function(beta, lambda, pi, sigma_v, rho, X, Z) {
  if (length(beta) != ncol(X)) stop("Incorrect beta dimension.")
  if (length(pi) != ncol(Z)) stop("Incorrect pi dimension.")
  if (!is.finite(sigma_v) || sigma_v <= 0) {
    stop("sigma_v must be strictly positive.")
  }
  if (!is.finite(rho) || abs(rho) >= 1) {
    stop("rho must lie strictly inside (-1,1).")
  }

  out <- c(
    as.numeric(beta),
    as.numeric(lambda),
    as.numeric(pi),
    log(as.numeric(sigma_v)),
    atanh(as.numeric(rho))
  )
  names(out) <- .sbivml_parameter_names(X, Z)
  out
}

.sbivml_read_parameters <- function(par, X, Z) {
  ii <- .sbivml_parameter_index(X, Z)
  beta <- as.numeric(par[ii$beta])
  names(beta) <- colnames(X)

  pi_hat <- as.numeric(par[ii$pi])
  names(pi_hat) <- colnames(Z)

  log_sigma_v <- as.numeric(par[ii$log_sigma_v])
  rho_raw <- as.numeric(par[ii$rho_raw])

  list(
    beta = beta,
    lambda = as.numeric(par[ii$lambda]),
    pi = pi_hat,
    log_sigma_v = log_sigma_v,
    rho_raw = rho_raw,
    sigma_v = exp(log_sigma_v),
    rho = tanh(rho_raw),
    index = ii
  )
}

.sbivml_structural_vector <- function(par, X, Z) {
  pp <- .sbivml_read_parameters(par, X, Z)
  out <- c(
    unname(pp$beta),
    unname(pp$lambda),
    unname(pp$pi),
    unname(pp$sigma_v),
    unname(pp$rho)
  )
  names(out) <- .sbivml_structural_names(X, Z)
  out
}

.sbivml_structural_jacobian <- function(par, X, Z) {
  pp <- .sbivml_read_parameters(par, X, Z)
  p <- length(par)
  J <- diag(p)
  rownames(J) <- .sbivml_structural_names(X, Z)
  colnames(J) <- names(par)
  J[p - 1L, p - 1L] <- pp$sigma_v
  J[p, p] <- 1 - pp$rho^2
  J
}

.sbivml_joint_bounds <- function(problem, X, Z) {
  ii <- .sbivml_parameter_index(X, Z)
  p <- ii$p

  lower <- rep(-Inf, p)
  upper <- rep(Inf, p)
  lower[ii$lambda] <- problem$lambda_space$lower
  upper[ii$lambda] <- problem$lambda_space$upper

  names(lower) <- .sbivml_parameter_names(X, Z)
  names(upper) <- names(lower)

  list(
    lower = lower,
    upper = upper,
    spatial = problem$lambda_space
  )
}

.sbivml_clip_lambda_start <- function(out, bounds) {
  jlam <- which(names(out) == "lambda")
  if (length(jlam) != 1L) stop("Could not locate lambda in starting values.")
  lo <- bounds$lower[jlam]
  hi <- bounds$upper[jlam]
  width <- hi - lo
  eps <- max(1e-8, 1e-6 * abs(width))
  out[jlam] <- min(max(out[jlam], lo + eps), hi - eps)
  out
}

.sbivml_make_start <- function(y, X, xend, Z, bounds, problem) {
  fs <- stats::lm.fit(x = as.matrix(Z), y = as.numeric(xend))
  pi_hat <- as.numeric(fs$coefficients)
  pi_hat[!is.finite(pi_hat)] <- 0

  vhat <- as.numeric(xend - Z %*% pi_hat)
  sigma_hat <- sqrt(mean(vhat^2))
  if (!is.finite(sigma_hat) || sigma_hat <= 0) sigma_hat <- 1

  beta_start <- rep(0, ncol(X))
  fit0 <- try(
    stats::glm.fit(x = as.matrix(X), y = as.numeric(y), family = stats::binomial(link = "probit")),
    silent = TRUE
  )
  if (!inherits(fit0, "try-error") &&
      length(fit0$coefficients) == ncol(X)) {
    bb <- as.numeric(fit0$coefficients)
    bb[!is.finite(bb)] <- 0
    beta_start <- bb
  }

  lambda_start <- 0
  Wy <- as.numeric(problem$W %*% as.numeric(y))
  sy <- stats::sd(as.numeric(y))
  swy <- stats::sd(Wy)
  if (is.finite(sy) && is.finite(swy) && sy > 0 && swy > 0) {
    cc <- suppressWarnings(stats::cor(as.numeric(y), Wy))
    if (is.finite(cc)) lambda_start <- as.numeric(cc)
  }

  out <- .sbivml_make_parameter_vector(
    beta = beta_start,
    lambda = lambda_start,
    pi = pi_hat,
    sigma_v = sigma_hat,
    rho = 0,
    X = X,
    Z = Z
  )

  .sbivml_clip_lambda_start(out, bounds)
}

.sbivml_structural_start_to_internal <- function(start, X, Z, bounds) {
  p <- length(.sbivml_structural_names(X, Z))
  if (length(start) != p) {
    stop(
      "Incorrect number of starting values. Expected ", p,
      " values ordered as beta, lambda, pi, sigma_v, rho."
    )
  }

  K <- ncol(X)
  L <- ncol(Z)
  beta <- start[seq_len(K)]
  lambda <- start[K + 1L]
  pi <- start[(K + 2L):(K + 1L + L)]
  sigma_v <- start[K + L + 2L]
  rho <- start[K + L + 3L]

  out <- .sbivml_make_parameter_vector(
    beta = beta, lambda = lambda, pi = pi,
    sigma_v = sigma_v, rho = rho, X = X, Z = Z
  )
  .sbivml_clip_lambda_start(out, bounds)
}

