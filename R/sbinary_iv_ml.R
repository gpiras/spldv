#' @rdname sbinary_iv_ml
#' @method vcov binivml
#' @export
vcov.binivml <- function(object,
                        vce = c("hessian", "sandwich"),
                        R = 500L,
                        seed = 123L,
                        ...) {
  vce <- match.arg(vce)

  if (vce == "hessian") {
    V <- object$opt$vcov_structural
    if (is.null(V) || !isTRUE(object$opt$hessian_valid)) {
      stop(
        "A valid positive-definite fixed-order Hessian is not available. ",
        "Re-estimate with hessian = TRUE and inspect the optimizer diagnostics."
      )
    }
    V <- as.matrix(V)
    attr(V, "vce") <- "hessian"
    return(V)
  }

  if (!identical(object$method, "ME")) {
    stop(
      "The operational sandwich covariance is currently implemented ",
      "for method = 'ME' only."
    )
  }

  if (!is.numeric(R) || length(R) != 1L || !is.finite(R) || R < 1) {
    stop("'R' must be a positive integer.")
  }
  R <- as.integer(R)

  if (!is.numeric(seed) || length(seed) != 1L || !is.finite(seed)) {
    stop("'seed' must be a finite integer.")
  }
  seed <- as.integer(seed)

  if (!isTRUE(object$opt$hessian_valid) ||
      is.null(object$opt$hessian) ||
      is.null(object$opt$vcov_optimizer)) {
    stop(
      "Sandwich covariance estimation requires a valid positive-definite ",
      "fixed-order Hessian. Re-estimate with hessian = TRUE."
    )
  }

  p <- length(object$opt$par)
  if (R <= p + 2L) {
    stop(
      "'R' must exceed the optimizer parameter dimension + 2. ",
      "For this model use R > ", p + 2L, "."
    )
  }

  draws <- .sbivml_make_sandwich_draws(
    n             = length(object$y),
    B             = R,
    seed          = seed,
    preserve_seed = TRUE
  )

  sand <- .sbivml_operational_sandwich(
    fit       = object$opt,
    engine    = object$engine,
    rule      = object$rule,
    X         = object$X,
    xend      = object$xend,
    Z         = object$Z,
    problem   = object$problem,
    endog_col = object$endog_col,
    draws     = draws
  )

  if (!isTRUE(sand$ok)) {
    stop("Sandwich covariance estimation failed: ", sand$reason)
  }

  V <- as.matrix(sand$vcov_structural)
  attr(V, "vce") <- "sandwich"
  attr(V, "R") <- R
  attr(V, "seed") <- seed
  attr(V, "n_inner_valid") <- sand$n_inner_valid
  attr(V, "inner_valid_rate") <- sand$inner_valid_rate
  attr(V, "scaling_identity_error") <- sand$scaling_identity_error
  attr(V, "elapsed") <- sand$elapsed
  V
}

