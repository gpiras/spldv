.sbivml_build_me_pm_objects <- function(par, y, X, xend, Z, problem) {
  base <- .sbivml_joint_base(
    par,
    y        = y,
    X        = X,
    xend     = xend,
    Z        = Z,
    W        = problem$W,
    need_pm  = TRUE,
    need_vc  = FALSE,
    pm_cache = problem$pm_cache
  )

  if (is.null(base)) return(NULL)

  lower <- ifelse(y == 1, -Inf, base$mu)
  upper <- ifelse(y == 1, base$mu, Inf)

  dlower <- matrix(0, nrow = base$n, ncol = base$npar)
  dupper <- matrix(0, nrow = base$n, ncol = base$npar)
  dlower[y == 0, ] <- base$dmu[y == 0, , drop = FALSE]
  dupper[y == 1, ] <- base$dmu[y == 1, , drop = FALSE]

  list(
    base       = base,
    lower      = lower,
    upper      = upper,
    dlower     = dlower,
    dupper     = dupper,
    Prec       = base$Prec,
    dPrec_list = base$dPrec_list
  )
}

.sbivml_build_me_vc_objects <- function(par, y, X, xend, Z, problem) {
  base <- .sbivml_joint_base(
    par,
    y        = y,
    X        = X,
    xend     = xend,
    Z        = Z,
    W        = problem$W,
    need_pm  = FALSE,
    need_vc  = TRUE,
    pm_cache = problem$pm_cache
  )
  if (is.null(base)) return(NULL)

  lower  <- ifelse(y == 1, -Inf, base$mu)
  upper  <- ifelse(y == 1, base$mu, Inf)
  dlower <- matrix(0, nrow = base$n, ncol = base$npar)
  dupper <- matrix(0, nrow = base$n, ncol = base$npar)
  dlower[y == 0, ] <- base$dmu[y == 0, , drop = FALSE]
  dupper[y == 1, ] <- base$dmu[y == 1, , drop = FALSE]

  list(
    base   = base,
    lower  = lower,
    upper  = upper,
    dlower = dlower,
    dupper = dupper
  )
}

.sbivml_eval_me_pm <- function(par, y, X, xend, Z, problem,
                              rule = c("N", "M"),
                              fixed_order = NULL,
                              check_factor = FALSE) {
  rule <- match.arg(rule)
  pm   <- .sbivml_build_me_pm_objects(par, y, X, xend, Z, problem)

  fail <- function(order = NULL) {
    list(
      logLik            = -Inf,
      gradient          = rep(NA_real_, length(par)),
      order             = order,
      ord_stat          = NULL,
      ord_fill_relative = NULL,
      rule              = rule,
      engine            = "ME_PM",
      amd_applied       = identical(rule, "M") && is.null(fixed_order),
      amd_nontrivial    = NA
    )
  }

  if (is.null(pm)) return(fail())
  n <- pm$base$n

  if (!is.null(fixed_order)) {
    if (!.sbivml_valid_perm(fixed_order, n)) return(fail())
    ord_stat   <- as.integer(fixed_order)
    append_amd <- FALSE
  } else if (rule == "N") {
    ord_stat   <- seq_len(n)
    append_amd <- FALSE
  } else {
    diagOmega <- .sbivml_exact_diag_omega(pm$base)
    if (is.null(diagOmega)) return(fail())

    ord_stat <- .sbivml_mg_me_order(
      pm$lower,
      pm$upper,
      diagOmega,
      precision_storage = TRUE
    )
    append_amd <- TRUE
  }

  if (is.null(ord_stat) || !.sbivml_valid_perm(ord_stat, n)) return(fail())

  ff <- .sbivml_pm_factor(
    pm$Prec,
    ord_stat,
    append_amd   = append_amd,
    check_factor = check_factor
  )
  if (is.null(ff)) return(fail(ord_stat))

  dP <- lapply(
    pm$dPrec_list,
    function(M) {
      if (is.null(M)) NULL else
        M[ff$ord_final, ff$ord_final, drop = FALSE]
    }
  )

  dU <- .sbivml_chol_upper_derivative_list(
    dP,
    ff$U,
    rho_index = pm$base$idx_rho_raw,
    rho       = pm$base$pp$rho
  )
  if (is.null(dU)) return(fail(ff$ord_final))

  rec <- .sbivml_me_pm_grad_from_U(
    lower   = pm$lower[ff$ord_final],
    upper   = pm$upper[ff$ord_final],
    dlower  = pm$dlower[ff$ord_final, , drop = FALSE],
    dupper  = pm$dupper[ff$ord_final, , drop = FALSE],
    U       = ff$U,
    dU_list = dU
  )

  if (!is.finite(rec$logp) || any(!is.finite(rec$grad))) {
    return(fail(ff$ord_final))
  }

  list(
    logLik            = as.numeric(pm$base$log_fx + rec$logp),
    gradient          = as.numeric(pm$base$g_fx + rec$grad),
    order             = ff$ord_final,
    ord_stat          = ff$ord_stat,
    ord_fill_relative = ff$ord_fill_relative,
    rule              = rule,
    engine            = "ME_PM",
    amd_applied       = append_amd,
    amd_nontrivial    = ff$amd_nontrivial,
    nnz_U             = ff$nnz_U,
    nnz_P_upper       = ff$nnz_P_upper,
    fill_ratio        = if (ff$nnz_P_upper > 0) ff$nnz_U / ff$nnz_P_upper else NA_real_
  )
}

.sbivml_eval_me_vc <- function(par, y, X, xend, Z, problem,
                              rule = c("N", "M"),
                              fixed_order = NULL) {
  rule <- match.arg(rule)
  obj <- .sbivml_build_me_vc_objects(par, y, X, xend, Z, problem)

  fail <- function(order = NULL) {
    list(
      logLik            = -Inf,
      gradient          = rep(NA_real_, length(par)),
      order             = order,
      ord_stat          = NULL,
      ord_fill_relative = NULL,
      rule              = rule,
      engine            = "ME_VC",
      amd_applied       = FALSE,
      amd_nontrivial    = FALSE
    )
  }

  if (is.null(obj)) return(fail())
  base <- obj$base
  n <- base$n

  if (!is.null(fixed_order)) {
    if (!.sbivml_valid_perm(fixed_order, n)) return(fail())
    ord_final <- as.integer(fixed_order)
    ord_stat <- ord_final
  } else if (rule == "N") {
    ord_final <- seq_len(n)
    ord_stat <- ord_final
  } else {
    ord_stat <- .sbivml_mg_me_order(
      obj$lower,
      obj$upper,
      diag(base$Omega),
      precision_storage = FALSE
    )
    if (is.null(ord_stat) || !.sbivml_valid_perm(ord_stat, n)) return(fail())
    ord_final <- as.integer(ord_stat)
  }

  rec <- .sbivml_me_vc_grad(
    lower = obj$lower[ord_final],
    upper = obj$upper[ord_final],
    Omega = base$Omega[ord_final, ord_final, drop = FALSE],
    dlower = obj$dlower[ord_final, , drop = FALSE],
    dupper = obj$dupper[ord_final, , drop = FALSE],
    dOmega_list = lapply(
      base$dOmega_list,
      function(M) {
        if (is.null(M)) NULL else M[ord_final, ord_final, drop = FALSE]
      }
    ),
    rho_index = base$idx_rho_raw,
    rho = base$pp$rho
  )

  if (!is.finite(rec$logp) || any(!is.finite(rec$grad))) {
    return(fail(ord_final))
  }

  list(
    logLik = as.numeric(base$log_fx + rec$logp),
    gradient = as.numeric(base$g_fx + rec$grad),
    order = as.integer(ord_final),
    ord_stat = as.integer(ord_stat),
    ord_fill_relative = seq_len(n),
    rule = rule,
    engine = "ME_VC",
    amd_applied = FALSE,
    amd_nontrivial = FALSE
  )
}

.sbivml_eval_ris <- function(par, y, X, xend, Z, problem, draws,
                            engine = c("RIS_PM", "RIS_VC"),
                            fixed_order = NULL) {
  engine <- match.arg(engine)
  ee <- if (engine == "RIS_PM") "pm" else "vc"

  base <- .sbivml_joint_base(
    par,
    y = y,
    X = X,
    xend = xend,
    Z = Z,
    W = problem$W,
    need_pm = ee == "pm",
    need_vc = ee == "vc",
    pm_cache = problem$pm_cache
  )

  fail <- function(order = fixed_order) {
    list(
      logLik = -Inf,
      gradient = rep(NA_real_, length(par)),
      order = order,
      ord_stat = order,
      ord_fill_relative = if (!is.null(order)) seq_along(order) else NULL,
      rule = "M",
      engine = engine,
      amd_applied = FALSE,
      amd_nontrivial = FALSE
    )
  }

  if (is.null(base)) return(fail())

  q <- 2 * as.integer(y) - 1
  s <- as.numeric(q * base$mu)
  ds <- base$dmu * q

  if (is.null(fixed_order)) {
    diagOmega <- if (ee == "pm") {
      .sbivml_exact_diag_omega(base)
    } else {
      diag(base$Omega)
    }
    if (is.null(diagOmega)) return(fail())

    ord <- .sbivml_mg_ris_order(
      s,
      diagOmega,
      precision_storage = identical(ee, "pm")
    )
  } else {
    ord <- as.integer(fixed_order)
  }

  if (is.null(ord) || !.sbivml_valid_perm(ord, base$n)) return(fail(ord))

  q_ord <- q[ord]

  if (ee == "pm") {
    Prec_ord <- .sbivml_sign_adjust(
      base$Prec[ord, ord, drop = FALSE],
      q_ord
    )
    dPrec_ord <- lapply(
      base$dPrec_list,
      function(M) {
        if (is.null(M)) NULL else
          .sbivml_sign_adjust(M[ord, ord, drop = FALSE], q_ord)
      }
    )

    ff <- .sbivml_chol_upper(
      Prec_ord,
      amd = FALSE,
      check_factor = FALSE
    )

    if (is.null(ff) || !identical(ff$perm, seq_len(base$n))) {
      return(fail(ord))
    }

    dU <- .sbivml_chol_upper_derivative_list(
      dPrec_ord,
      ff$U,
      rho_index = base$idx_rho_raw,
      rho = base$pp$rho
    )
    if (is.null(dU)) return(fail(ord))

    rec <- .sbivml_ris_pm_grad_from_U(
      s = s[ord],
      ds = ds[ord, , drop = FALSE],
      U = ff$U,
      dU_list = dU,
      draws = draws[ord, , drop = FALSE]
    )
    nnz_U <- ff$nnz_U
  } else {
    sign_ord <- tcrossprod(q_ord, q_ord)
    Omega_ord <- base$Omega[ord, ord, drop = FALSE] * sign_ord
    dOmega_ord <- lapply(
      base$dOmega_list,
      function(M) {
        if (is.null(M)) NULL else M[ord, ord, drop = FALSE] * sign_ord
      }
    )

    rec <- .sbivml_ris_vc_grad(
      s = s[ord],
      ds = ds[ord, , drop = FALSE],
      Omega = Omega_ord,
      dOmega_list = dOmega_ord,
      draws = draws[ord, , drop = FALSE],
      rho_index = base$idx_rho_raw,
      rho = base$pp$rho
    )
    nnz_U <- NA_integer_
  }

  if (!is.finite(rec$logp) || any(!is.finite(rec$grad))) {
    return(fail(ord))
  }

  list(
    logLik = as.numeric(base$log_fx + rec$logp),
    gradient = as.numeric(base$g_fx + rec$grad),
    order = as.integer(ord),
    ord_stat = as.integer(ord),
    ord_fill_relative = seq_len(base$n),
    rule = "M",
    engine = engine,
    amd_applied = FALSE,
    amd_nontrivial = FALSE,
    nnz_U = nnz_U
  )
}

## ========================================== -
## Generic optimizer and fixed-order Hessian ----
## ========================================== -

.sbivml_optimize_joint <- function(start, bounds, evaluator, fixed_builder,
                                  label, X, Z,
                                  maxit = 800L, factr = 1e7, pgtol = 1e-6,
                                  compute_hessian = TRUE) {
  cache         <- new.env(parent = emptyenv())
  cache$par     <- NULL
  cache$ans     <- NULL
  n_eval_unique <- 0L
  n_invalid     <- 0L

  eval_cached <- function(par) {
    if (!is.null(cache$par) &&
        length(cache$par) == length(par) &&
        max(abs(cache$par - par)) < 1e-14) {
      return(cache$ans)
    }

    ans <- evaluator(par)
    n_eval_unique <<- n_eval_unique + 1L

    valid <- is.list(ans) &&
      is.finite(ans$logLik) &&
      !is.null(ans$gradient) &&
      length(ans$gradient) == length(par) &&
      all(is.finite(ans$gradient))

    if (!valid) n_invalid <<- n_invalid + 1L

    cache$par <- as.numeric(par)
    cache$ans <- ans
    ans
  }

  fn <- function(par) {
    ans <- eval_cached(par)
    if (!is.finite(ans$logLik)) return(1e100)
    -ans$logLik
  }

  gr <- function(par) {
    ans <- eval_cached(par)
    if (!is.finite(ans$logLik) ||
        is.null(ans$gradient) ||
        length(ans$gradient) != length(par) ||
        any(!is.finite(ans$gradient))) {
      stop("Invalid criterion/gradient during ", label, ".")
    }
    -ans$gradient
  }

  t0  <- proc.time()[["elapsed"]]
  opt <- try(stats::optim(par     = start,
                          fn      = fn,
                          gr      = gr,
                          method  = "L-BFGS-B",
                          lower   = bounds$lower,
                          upper   = bounds$upper,
                          control = list(maxit = maxit,
                                         factr = factr,
                                         pgtol = pgtol)),
             silent = TRUE)
  fit_elapsed <- proc.time()[["elapsed"]] - t0

  fail <- function(code, msg, par = rep(NA_real_, length(start))) {
    list(
      fit_ok          = FALSE,
      optimizer_clean = FALSE,
      convergence     = code,
      message         = msg,
      par             = par,
      logLik          = NA_real_,
      vc_ok           = FALSE,
      hessian_valid   = FALSE,
      fit_elapsed     = fit_elapsed,
      hessian_elapsed = NA_real_,
      bounds          = bounds,
      start           = start
    )
  }

  if (inherits(opt, "try-error")) {
    return(fail(98L, as.character(opt)))
  }

  final <- try(eval_cached(opt$par), silent = TRUE)
  if (inherits(final, "try-error") ||
      !is.list(final) ||
      !is.finite(final$logLik) ||
      any(!is.finite(final$gradient)) ||
      is.null(final$order)) {
    return(fail(
      97L,
      "Optimizer returned an invalid final criterion, gradient, or ordering.",
      opt$par
    ))
  }

  fixed_eval <- fixed_builder(final$order)
  if (!is.function(fixed_eval)) {
    return(fail(
      96L,
      "Could not construct fixed-order endpoint evaluator.",
      opt$par
    ))
  }

  H <- NULL
  Vopt <- NULL
  Vstruct <- NULL
  se_struct <- NULL
  vc_ok <- FALSE
  hessian_pd <- FALSE
  hessian_min_eig <- NA_real_
  hessian_rcond <- NA_real_
  hessian_elapsed <- 0

  if (isTRUE(compute_hessian)) {
    hcache <- new.env(parent = emptyenv())
    hcache$par <- NULL
    hcache$ans <- NULL

    heval <- function(par) {
      if (!is.null(hcache$par) &&
          length(hcache$par) == length(par) &&
          max(abs(hcache$par - par)) < 1e-14) {
        return(hcache$ans)
      }
      ans <- fixed_eval(par)
      hcache$par <- as.numeric(par)
      hcache$ans <- ans
      ans
    }

    hfn <- function(par) {
      ans <- heval(par)
      if (!is.finite(ans$logLik)) return(1e100)
      -ans$logLik
    }

    hgr <- function(par) {
      ans <- heval(par)
      if (!is.finite(ans$logLik) || any(!is.finite(ans$gradient))) {
        stop("Invalid fixed-order score during Hessian for ", label)
      }
      -ans$gradient
    }

    th0 <- proc.time()[["elapsed"]]
    Hraw <- try(
      stats::optimHess(opt$par, fn = hfn, gr = hgr),
      silent = TRUE
    )
    hessian_elapsed <- proc.time()[["elapsed"]] - th0

    if (!inherits(Hraw, "try-error") &&
        is.matrix(Hraw) &&
        all(dim(Hraw) == c(length(start), length(start))) &&
        all(is.finite(Hraw))) {
      H <- 0.5 * (Hraw + t(Hraw))
      ee <- try(
        eigen(H, symmetric = TRUE, only.values = TRUE)$values,
        silent = TRUE
      )

      if (!inherits(ee, "try-error") && all(is.finite(ee))) {
        hessian_min_eig <- min(ee)
        tol_pd <- 1e-8 * max(1, max(abs(ee)))
        hessian_pd <- hessian_min_eig > tol_pd
      }

      hessian_rcond <- tryCatch(rcond(H), error = function(e) NA_real_)

      if (isTRUE(hessian_pd)) {
        RR <- try(chol(H), silent = TRUE)
        if (!inherits(RR, "try-error")) {
          Vopt0 <- try(chol2inv(RR), silent = TRUE)
          if (!inherits(Vopt0, "try-error") && all(is.finite(Vopt0))) {
            J <- .sbivml_structural_jacobian(opt$par, X = X, Z = Z)
            VV <- J %*% Vopt0 %*% t(J)
            VV <- 0.5 * (VV + t(VV))
            dd <- diag(VV)

            if (all(is.finite(dd)) && all(dd > 0)) {
              Vopt <- Vopt0
              Vstruct <- VV
              se_struct <- sqrt(dd)
              names(se_struct) <- rownames(J)
              rownames(Vstruct) <- colnames(Vstruct) <- rownames(J)
              vc_ok <- TRUE
            }
          }
        }
      }
    }
  }

  score <- as.numeric(final$gradient)
  names(score) <- names(start)
  pscore <- .sbivml_projected_score(
    opt$par, score, bounds$lower, bounds$upper
  )
  bflags <- .sbivml_boundary_flags(
    opt$par, bounds$lower, bounds$upper
  )

  optimizer_clean <- isTRUE(opt$convergence == 0L)

  list(
    fit_ok = TRUE,
    optimizer_clean = optimizer_clean,
    converged = optimizer_clean,
    estimator = label,
    convergence = as.integer(opt$convergence),
    message = as.character(opt$message),
    fit_elapsed = fit_elapsed,
    hessian_elapsed = hessian_elapsed,
    total_elapsed = fit_elapsed + hessian_elapsed,
    counts = opt$counts,
    par = setNames(as.numeric(opt$par), names(start)),
    coef_structural = .sbivml_structural_vector(opt$par, X = X, Z = Z),
    logLik = final$logLik,
    score = score,
    score_norm = sqrt(sum(score^2)),
    score_maxabs = max(abs(score)),
    projected_score = pscore,
    projected_score_norm = sqrt(sum(pscore^2)),
    projected_score_maxabs = max(abs(pscore)),
    boundary_flags = bflags,
    any_boundary = any(bflags),
    final_order = final$order,
    final_order_signature = .sbivml_perm_signature(final$order),
    final_ord_stat = final$ord_stat,
    final_ord_fill_relative = final$ord_fill_relative,
    final_amd_applied = isTRUE(final$amd_applied),
    final_amd_nontrivial = isTRUE(final$amd_nontrivial),
    final_nnz_U = if (!is.null(final$nnz_U)) final$nnz_U else NA_integer_,
    final_nnz_P_upper = if (!is.null(final$nnz_P_upper)) final$nnz_P_upper else NA_integer_,
    final_fill_ratio = if (!is.null(final$fill_ratio)) final$fill_ratio else NA_real_,
    n_eval_unique = n_eval_unique,
    n_invalid = n_invalid,
    hessian = H,
    hessian_fixed_order = TRUE,
    hessian_pd = hessian_pd,
    hessian_min_eig = hessian_min_eig,
    hessian_rcond = hessian_rcond,
    vcov_optimizer = if (isTRUE(vc_ok)) Vopt else NULL,
    vcov_structural = if (isTRUE(vc_ok)) Vstruct else NULL,
    se_structural = if (isTRUE(vc_ok)) se_struct else NULL,
    vc_ok = isTRUE(vc_ok),
    hessian_valid = isTRUE(vc_ok),
    bounds = bounds,
    start = start,
    final = final
  )
}

.sbivml_fit_joint <- function(engine, rule,
                             y, X, xend, Z, problem,
                             draws = NULL,
                             start = NULL,
                             maxit = 800L,
                             factr = 1e7,
                             pgtol = 1e-6,
                             compute_hessian = TRUE) {
  valid <- (
    (engine %in% c("ME_PM", "ME_VC") && rule %in% c("N", "M")) ||
    (engine %in% c("RIS_PM", "RIS_VC") && rule == "M")
  )
  if (!valid) stop("Unsupported estimator combination: ", engine, "_", rule)

  if (engine %in% c("RIS_PM", "RIS_VC") && is.null(draws)) {
    stop("RIS requires simulation draws.")
  }

  bounds <- .sbivml_joint_bounds(problem, X = X, Z = Z)
  if (is.null(start)) {
    start <- .sbivml_make_start(y, X, xend, Z, bounds, problem)
  }

  evaluator <- switch(
    engine,
    ME_PM = function(par) {.sbivml_eval_me_pm(par, y, X, xend, Z, problem, rule = rule)},
    ME_VC = function(par) {.sbivml_eval_me_vc(par, y, X, xend, Z, problem, rule = rule)},
    RIS_PM = function(par) {.sbivml_eval_ris(par, y, X, xend, Z, problem, draws, engine = "RIS_PM")},
    RIS_VC = function(par) {.sbivml_eval_ris(par, y, X, xend, Z, problem, draws, engine = "RIS_VC")}
  )

  fixed_builder <- switch(
    engine,
    ME_PM  = function(ord) {function(par) {.sbivml_eval_me_pm(par, y, X, xend, Z, problem, rule = rule, fixed_order = ord)}},
    ME_VC  = function(ord) {function(par) {.sbivml_eval_me_vc(par, y, X, xend, Z, problem, rule = rule, fixed_order = ord)}},
    RIS_PM = function(ord) {function(par) {.sbivml_eval_ris(par, y, X, xend, Z, problem, draws, engine = "RIS_PM", fixed_order = ord)}},
    RIS_VC = function(ord) {function(par) {.sbivml_eval_ris(par, y, X, xend, Z, problem, draws, engine = "RIS_VC", fixed_order = ord)}}
  )

  label <- if (engine == "ME_PM" && rule == "M") {"ME_PM_MD"} else {paste(engine, rule, sep = "_")}

  fit <- .sbivml_optimize_joint(
    start           = start,
    bounds          = bounds,
    evaluator       = evaluator,
    fixed_builder   = fixed_builder,
    label           = label,
    X               = X,
    Z               = Z,
    maxit           = maxit,
    factr           = factr,
    pgtol           = pgtol,
    compute_hessian = compute_hessian
  )

  if (engine %in% c("RIS_PM", "RIS_VC")) {fit$ris_draws <- ncol(draws)}
  fit
}

## ===================================================== -
## Operational model-based sandwich covariance (ME only) ----
## ===================================================== -

.sbivml_make_sandwich_draws <- function(n, B = 500L, seed = 123L,
                                       preserve_seed = TRUE) {
  if (B < 1L) stop("B must be positive.")

  old_exists <- exists(
    ".Random.seed", envir = .GlobalEnv, inherits = FALSE
  )
  if (isTRUE(preserve_seed)) {
    old <- if (old_exists) get(".Random.seed", envir = .GlobalEnv) else NULL
    on.exit({
      if (old_exists) {
        assign(".Random.seed", old, envir = .GlobalEnv)
      } else if (exists(".Random.seed", envir = .GlobalEnv, inherits = FALSE)) {
        rm(".Random.seed", envir = .GlobalEnv)
      }
    }, add = TRUE)
  }

  set.seed(seed)
  raw <- matrix(stats::rnorm(2L * n * B), nrow = 2L * n, ncol = B)
  list(z_v   = raw[seq_len(n), , drop = FALSE], 
       z_eta = raw[n + seq_len(n), , drop = FALSE],
       seed  = as.integer(seed))
}

.sbivml_simulate_conditional_batch <- function(par, X, Z, problem,
                                              endog_col, draws) {
  pp <- .sbivml_read_parameters(par, X, Z)
  n <- nrow(X)
  B <- ncol(draws$z_v)

  if (nrow(draws$z_v) != n || nrow(draws$z_eta) != n ||
      ncol(draws$z_eta) != B) {
    stop("Invalid sandwich draw dimensions.")
  }
  if (length(endog_col) != 1L || is.na(endog_col) ||
      endog_col < 1L || endog_col > ncol(X)) {
    stop("Invalid endogenous-regressor column index.")
  }
  if (!(pp$lambda > problem$lambda_space$lower &&
        pp$lambda < problem$lambda_space$upper)) {
    stop("Sandwich simulation lambda lies outside the admissible interval.")
  }

  V    <- pp$sigma_v * draws$z_v
  E    <- pp$rho * draws$z_v + sqrt(1 - pp$rho^2) * draws$z_eta
  zpi  <- as.numeric(Z %*% pp$pi)
  Xend <- zpi + V

  beta_end <- pp$beta[endog_col]
  if (ncol(X) == 1L) {
    fixed_rhs <- rep(0, n)
  } else {
    fixed_rhs <- as.numeric(X[, -endog_col, drop = FALSE] %*% pp$beta[-endog_col])
  }
  RHS <- fixed_rhs + beta_end * Xend + E

  A        <- Matrix::drop0(problem$pm_cache$I - pp$lambda * problem$W)
  A_factor <- .sbivml_factor_A(A)
  Ystar0   <- .sbivml_solve_A(A, RHS, factor = A_factor)
  Ystar    <- if (is.null(Ystar0)) NULL else tryCatch(as.matrix(Ystar0), error = function(e) NULL)
  if (is.null(Ystar) || any(!is.finite(Ystar))) {return(NULL)}

  list(y = (Ystar > 0) * 1, xend = Xend)
}

.sbivml_fixed_me_score <- function(par, engine, rule, y, X, xend, Z,
                                  problem, order) {
  ans <- switch(engine, 
                ME_PM = .sbivml_eval_me_pm(par, y, X, xend, Z, problem,
                                          rule = rule, fixed_order = order),
                ME_VC = .sbivml_eval_me_vc(par, y, X, xend, Z, problem,
                                          rule = rule, fixed_order = order),
                stop("Operational sandwich is implemented for ME only.")
  )

  if (!is.finite(ans$logLik) || length(ans$gradient) != length(par) || 
      any(!is.finite(ans$gradient))) {return(NULL)}
  as.numeric(ans$gradient)
}

.sbivml_operational_sandwich <- function(fit, engine, rule,
                                        X, xend, Z, problem,
                                        endog_col, draws) {
  if (!engine %in% c("ME_PM", "ME_VC")) {
    return(list(ok = FALSE, reason = "operational sandwich is available for ME only"))
  }
  if (!isTRUE(fit$fit_ok) || is.null(fit$par) ||
      is.null(fit$final_order) || is.null(fit$hessian) ||
      !isTRUE(fit$hessian_valid) || is.null(fit$vcov_optimizer)) {
    return(list(ok = FALSE, reason = "fit/order/positive-definite Hessian unavailable"))
  }

  p <- length(fit$par)
  B <- ncol(draws$z_v)
  if (B <= p + 2L) {
    return(list(ok = FALSE, 
                reason = "R must exceed the optimizer parameter dimension + 2",
                n_inner_requested = B))
  }

  sim <- try(
    .sbivml_simulate_conditional_batch(
      fit$par, X, Z, problem, endog_col, draws
    ),
    silent = TRUE
  )
  if (inherits(sim, "try-error") || is.null(sim)) {
    return(list(ok = FALSE, reason = "conditional sandwich simulation failed"))
  }

  scores <- matrix(NA_real_, nrow = B, ncol = p)
  valid  <- logical(B)
  t0     <- proc.time()[["elapsed"]]

  for (b in seq_len(B)) {
    Xb <- X
    Xb[, endog_col] <- sim$xend[, b]
    sc <- try(.sbivml_fixed_me_score(fit$par, engine, rule, 
                                    y       = sim$y[, b],
                                    X       = Xb,
                                    xend    = sim$xend[, b],
                                    Z       = Z,
                                    problem = problem,
                                    order   = fit$final_order),
              silent = TRUE)
    if (inherits(sc, "try-error") || is.null(sc) ||
        length(sc) != p || any(!is.finite(sc))) {next}
    scores[b, ] <- sc
    valid[b]    <- TRUE
  }
  elapsed <- proc.time()[["elapsed"]] - t0

  S <- scores[valid, , drop = FALSE]
  nvalid <- nrow(S)
  if (nvalid <= p + 2L) {
    return(list(
      ok = FALSE,
      reason = "too few valid inner score draws",
      n_inner_requested = B,
      n_inner_valid = nvalid,
      elapsed = elapsed
    ))
  }

  K <- stats::cov(S)
  if (any(!is.finite(K))) {
    return(list(
      ok = FALSE, reason = "non-finite sandwich score covariance",
      n_inner_requested = B, n_inner_valid = nvalid, elapsed = elapsed
    ))
  }
  K <- 0.5 * (K + t(K))

  H <- 0.5 * (fit$hessian + t(fit$hessian))
  Hinv <- fit$vcov_optimizer
  if (is.null(Hinv) || any(!is.finite(Hinv))) {
    return(list(
      ok = FALSE, reason = "inverse Hessian unavailable",
      n_inner_requested = B, n_inner_valid = nvalid, elapsed = elapsed
    ))
  }

  Vopt <- Hinv %*% K %*% Hinv
  Vopt <- 0.5 * (Vopt + t(Vopt))

  ## Same scaling identity in the MC experiment of the paper
  n <- nrow(Z)
  Jn <- H / n
  Kn <- K / n
  Vnorm0 <- try(solve(Jn), silent = TRUE)
  if (inherits(Vnorm0, "try-error")) {
    return(list(
      ok = FALSE, reason = "normalized Hessian solve failed",
      n_inner_requested = B, n_inner_valid = nvalid, elapsed = elapsed
    ))
  }
  Vnorm <- (Vnorm0 %*% Kn %*% t(Vnorm0)) / n
  scerr <- max(abs(Vopt - Vnorm)) / max(1, max(abs(Vopt)), max(abs(Vnorm)))
  if (!is.finite(scerr) || scerr > 1e-10) {
    return(list(
      ok = FALSE, reason = "sandwich n-scaling identity failed",
      n_inner_requested = B, n_inner_valid = nvalid,
      elapsed = elapsed, scaling_identity_error = scerr
    ))
  }

  J <- .sbivml_structural_jacobian(fit$par, X, Z)
  Vstruct <- J %*% Vopt %*% t(J)
  Vstruct <- 0.5 * (Vstruct + t(Vstruct))
  rownames(Vstruct) <- colnames(Vstruct) <- rownames(J)
  dd <- diag(Vstruct)
  if (any(!is.finite(dd)) || any(dd <= 0)) {
    return(list(
      ok = FALSE, reason = "invalid structural sandwich diagonal",
      n_inner_requested = B, n_inner_valid = nvalid,
      elapsed = elapsed, scaling_identity_error = scerr
    ))
  }

  se <- sqrt(dd)
  names(se) <- rownames(J)

  list(
    ok = TRUE,
    n_inner_requested = B,
    n_inner_valid = nvalid,
    inner_valid_rate = nvalid / B,
    elapsed = elapsed,
    mean_score = colMeans(S),
    K_optimizer = K,
    vcov_optimizer = Vopt,
    vcov_structural = Vstruct,
    se_structural = se,
    K_min_eig = tryCatch(
      min(eigen(K, symmetric = TRUE, only.values = TRUE)$values),
      error = function(e) NA_real_
    ),
    K_rcond = tryCatch(rcond(K), error = function(e) NA_real_),
    scaling_identity_error = scerr
  )
}

