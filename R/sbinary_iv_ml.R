#' @rdname sbinary_iv_ml
#' @method summary binivml
#' @export
summary.binivml <- function(object,
                           vce  = c("hessian", "sandwich"),
                           R    = 500L,
                           seed = 123L,
                           ...) {
  vce <- match.arg(vce)

  b  <- coef(object)
  V  <- vcov(object, vce = vce, R = R, seed = seed, ...)
  se <- sqrt(diag(V))
  z  <- b / se
  p  <- 2 * stats::pnorm(-abs(z))
  tab <- cbind(Estimate = b, `Std. error` = se, `z value` = z, `Pr(> z)` = p)

  out <- list(
    call = object$call,
    method = object$method,
    varcov = object$varcov,
    vce = vce,
    ordering = object$ordering,
    R = object$R,
    N = length(object$y),
    endog = object$endog,
    logLik = object$logLik,
    convergence = object$opt$convergence,
    message = object$opt$message,
    coefficients = tab,
    hessian_valid = object$opt$hessian_valid,
    optimizer_clean = object$opt$optimizer_clean,
    sandwich_R = if (vce == "sandwich") attr(V, "R") else NULL,
    sandwich_seed = if (vce == "sandwich") attr(V, "seed") else NULL,
    sandwich_n_valid = if (vce == "sandwich") attr(V, "n_inner_valid") else NULL,
    sandwich_valid_rate = if (vce == "sandwich") attr(V, "inner_valid_rate") else NULL,
    sandwich_scaling_error = if (vce == "sandwich") attr(V, "scaling_identity_error") else NULL
  )
  class(out) <- "summary.binivml"
  out
}

#' @rdname sbinary_iv_ml
#' @method print summary.binivml
#' @export
print.summary.binivml <- function(x,
                                 digits = max(3, getOption("digits") - 2),
                                 ...) {
  cat("--------------------------------------------\n")
  cat("Spatial binary probit with endogenous regressor\n")
  cat("Endogenous variable: ", x$endog, "\n", sep = "")
  cat(
    "Method: ", x$method,
    " | Cholesky: ", x$varcov,
    " | ordering: ", x$ordering,
    "\n", sep = ""
  )
  if (identical(x$method, "RIS")) {
    cat("RIS draws: ", x$R, "\n", sep = "")
  }
  cat("Standard errors: ", x$vce, "\n", sep = "")
  if (identical(x$vce, "sandwich")) {
    cat(
      "Sandwich inner draws: ", x$sandwich_R,
      " | valid: ", x$sandwich_n_valid,
      " (", format(100 * x$sandwich_valid_rate, digits = 4), "%)\n",
      sep = ""
    )
  }
  cat("Sample size: ", x$N, "\n", sep = "")
  cat("Convergence code: ", x$convergence, "\n", sep = "")
  cat("Log-Likelihood: ", format(x$logLik, digits = digits), "\n", sep = "")
  if (!isTRUE(x$optimizer_clean)) {
    cat("Optimizer message: ", x$message, "\n", sep = "")
  }
  if (!isTRUE(x$hessian_valid)) {
    cat("Note: a valid positive-definite Hessian is not available.\n")
  }
  cat("Estimates:\n")
  stats::printCoefmat(x$coefficients, digits = digits)
  cat("--------------------------------------------\n")
  invisible(x)
}
