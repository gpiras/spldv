.sbivml_joint_base <- function(par, y, X, xend, Z, W,
                              need_pm = TRUE,
                              need_vc = FALSE,
                              pm_cache = NULL) {
  n    <- length(y)
  K    <- ncol(X)
  L    <- ncol(Z)
  npar <- length(par)

  pp <- .sbivml_read_parameters(par, X, Z)
  ii <- pp$index

  if (!is.finite(pp$sigma_v) || pp$sigma_v <= 0 || !is.finite(pp$rho) || abs(pp$rho) >= 1) {
    return(NULL)
  }
  v      <- as.numeric(xend - Z %*% pp$pi)
  sigma2 <- pp$sigma_v^2

  log_fx <- -0.5 * n * log(2 * pi) - n * log(pp$sigma_v) - 0.5 * sum(v^2) / sigma2
  c_rho_sigma <- pp$rho / pp$sigma_v
  rhs <- as.numeric(X %*% pp$beta + c_rho_sigma * v)

  I_n <- if (!is.null(pm_cache) && !is.null(pm_cache$I)) pm_cache$I else Matrix::Diagonal(n)
  A        <- Matrix::drop0(I_n - pp$lambda * W)
  A_factor <- .sbivml_factor_A(A)

  RHS  <- cbind(rhs, X, Z, v)
  SOL0 <- .sbivml_solve_A(A, RHS, factor = A_factor)
  SOL  <- if (is.null(SOL0)) NULL else tryCatch(as.matrix(SOL0), error = function(e) NULL)

  if (is.null(SOL) || any(!is.finite(SOL))) return(NULL)

  mu   <- as.numeric(SOL[, 1L])
  ix_X0 <- 2L
  ix_X1 <- ix_X0 + K - 1L
  B_X   <- SOL[, ix_X0:ix_X1, drop = FALSE]

  ix_Z0 <- ix_X1 + 1L
  ix_Z1 <- ix_Z0 + L - 1L
  B_Z   <- SOL[, ix_Z0:ix_Z1, drop = FALSE]
  B_v   <- as.numeric(SOL[, ix_Z1 + 1L])
  B_W_mu0 <- .sbivml_solve_A(A, W %*% mu, factor = A_factor)
  B_W_mu <- if (is.null(B_W_mu0)) NULL else
    tryCatch(as.numeric(B_W_mu0), error = function(e) NULL)

  if (is.null(B_W_mu) || any(!is.finite(B_W_mu))) return(NULL)

  dmu <- matrix(0, nrow = n, ncol = npar)
  dmu[, ii$beta] <- B_X
  dmu[, ii$lambda] <- B_W_mu
  dmu[, ii$pi] <- -c_rho_sigma * B_Z
  dmu[, ii$log_sigma_v] <- -c_rho_sigma * B_v
  dmu[, ii$rho_raw] <- ((1 - pp$rho^2) / pp$sigma_v) * B_v

  vf <- 1 - pp$rho^2
  if (!is.finite(vf) || vf <= 1e-10) return(NULL)

  g_fx <- numeric(npar)
  g_fx[ii$pi] <- as.numeric(crossprod(Z, v)) / sigma2
  g_fx[ii$log_sigma_v] <- -n + sum(v^2) / sigma2

  out <- list(
    n = n,
    npar = npar,
    K = K,
    L = L,
    pp = pp,
    idx_beta = ii$beta,
    idx_lambda = ii$lambda,
    idx_pi = ii$pi,
    idx_lsigma = ii$log_sigma_v,
    idx_rho_raw = ii$rho_raw,
    v = v,
    log_fx = log_fx,
    g_fx = g_fx,
    X = X,
    A = A,
    A_factor = A_factor,
    pm_cache = pm_cache,
    mu = mu,
    dmu = dmu,
    vf = vf
  )

  if (isTRUE(need_pm)) {
    if (!is.null(pm_cache) &&
        !is.null(pm_cache$Wplus) &&
        !is.null(pm_cache$WtW) &&
        !is.null(pm_cache$I)) {
      S <- Matrix::drop0(
        pm_cache$I -
          pp$lambda * pm_cache$Wplus +
          pp$lambda^2 * pm_cache$WtW
      )
      dS_lambda <- Matrix::drop0(
        -pm_cache$Wplus +
          2 * pp$lambda * pm_cache$WtW
      )
    } else {
      S <- Matrix::crossprod(A)
      dS_lambda <- -(
        Matrix::crossprod(W, A) +
          Matrix::crossprod(A, W)
      )
    }

    Prec <- Matrix::drop0(S / vf)
    dPrec <- vector("list", npar)
    dPrec[[ii$lambda]] <- Matrix::drop0(dS_lambda / vf)

    out$Prec <- Prec
    out$dPrec_list <- dPrec
  }

  if (isTRUE(need_vc)) {
    B0 <- .sbivml_solve_A(
      A,
      if (!is.null(pm_cache) && !is.null(pm_cache$I)) {
        pm_cache$I
      } else {
        Matrix::Diagonal(n)
      },
      factor = A_factor
    )
    B <- if (is.null(B0)) NULL else tryCatch(as.matrix(B0), error = function(e) NULL)

    if (is.null(B) || any(!is.finite(B))) return(NULL)

    Omega <- vf * tcrossprod(B)
    dOmega <- vector("list", npar)

    X0 <- .sbivml_solve_A(
      A,
      W %*% Omega,
      factor = A_factor
    )
    Xlambda <- if (is.null(X0)) NULL else
      tryCatch(as.matrix(X0), error = function(e) NULL)

    if (is.null(Xlambda) || any(!is.finite(Xlambda))) return(NULL)

    dOmega[[ii$lambda]] <- Xlambda + t(Xlambda)

    out$B <- B
    out$Omega <- Omega
    out$dOmega_list <- dOmega
  }

  out
}

## ====================== -
