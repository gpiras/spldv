.sbivml_mills_upper <- function(x) {
  lp <- stats::pnorm(x, log.p = TRUE)
  lf <- stats::dnorm(x, log = TRUE)
  out <- exp(lf - lp)
  ifelse(is.finite(out), out, pmax(abs(x), .Machine$double.eps))
}

.sbivml_one_sided_terms <- function(lower, upper) {
  ## Stable exact terms for the only interval types appearing in the
  ## binary-probit recursion.
  ##
  ## (-Inf,b):
  ##   log P = log Phi(b)
  ##   m      = E[Z | Z<b] = -phi(b)/Phi(b)
  ##
  ## (a,Inf):
  ##   log P = log(1-Phi(a))
  ##   m      = E[Z | Z>a] =  phi(a)/(1-Phi(a))
  ##
  ## score_coef multiplies the derivative of the finite bound in d log P.
  ## mean_deriv_coef multiplies it in d m.
  if (is.infinite(lower) && lower < 0 && is.finite(upper)) {
    b    <- upper
    logP <- stats::pnorm(b, log.p = TRUE)
    if (!is.finite(logP)) return(NULL)

    mills <- exp(stats::dnorm(b, log = TRUE) - logP)
    if (!is.finite(mills)) return(NULL)

    return(list(
      logp            = logP,
      mean            = -mills,
      score_coef      = mills,
      mean_deriv_coef = mills * (b + mills),
      finite_side     = "upper"
    ))
  }

  if (is.finite(lower) && is.infinite(upper) &&upper > 0) {
    a   <- lower
    logP <- stats::pnorm(a, lower.tail = FALSE, log.p = TRUE)
    if (!is.finite(logP)) return(NULL)

    mills <- exp(stats::dnorm(a, log = TRUE) - logP)
    if (!is.finite(mills)) return(NULL)

    return(list(
      logp            = logP,
      mean            = mills,
      score_coef      = -mills,
      mean_deriv_coef = mills * (mills - a),
      finite_side     = "lower"
    ))
  }

  stop(
    "Expected a one-sided interval; got lower=", lower,
    ", upper=", upper
  )
}

.sbivml_make_ghk_draws <- function(n, R = 500L, seed = 123L,
                              preserve_seed = TRUE) {
  ## Nested paired antithetic draws:
  ## u1, 1-u1, u2, 1-u2, ...
  ##
  ## Hence, for a common seed, the R=500 matrix is exactly the first
  ## 500 columns of the R=1000 matrix.
  if (R < 1L) stop("R must be positive.")

  old_exists <- exists(".Random.seed", envir = .GlobalEnv, inherits = FALSE)

  if (isTRUE(preserve_seed)) {
    old <- if (old_exists) {
      get(".Random.seed", envir = .GlobalEnv)
    } else {
      NULL
    }

    on.exit({
      if (old_exists) {
        assign(".Random.seed", old, envir = .GlobalEnv)
      } else if (exists(
        ".Random.seed",
        envir = .GlobalEnv,
        inherits = FALSE
      )) {
        rm(".Random.seed", envir = .GlobalEnv)
      }
    }, add = TRUE)
  }

  set.seed(seed)

  half <- ceiling(R / 2)
  U0   <- matrix(stats::runif(n * half), nrow = n, ncol = half)
  U    <- matrix(NA_real_, nrow = n, ncol = 2L * half)
  odd  <- seq.int(1L, 2L * half, by = 2L)
  U[, odd] <- U0
  U[, odd + 1L] <- 1 - U0
  U <- U[, seq_len(R), drop = FALSE]
  pmin(pmax(U, .Machine$double.xmin), 1 - .Machine$double.eps)
}

.sbivml_spatial_parameter_space <- function(W, endpoint_margin = 1e-6) {
  ## Eigenvalues are used to construct the admissible interval for lambda.
  ## For asymmetric W, eigenvalues may be complex. Consistently with
  ## our previous function in spldv, the bounds are based on their real parts.
  sym     <- isTRUE(all.equal(as.matrix(W), t(as.matrix(W)), check.attributes = FALSE))
  ev      <- eigen(as.matrix(W), only.values = TRUE, symmetric = sym)$values
  ev_real <- Re(ev)
  eig_min <- min(ev_real)
  eig_max <- max(ev_real)
  if (!(is.finite(eig_min) &&
        is.finite(eig_max) &&
        eig_min < 0 &&
        eig_max > 0)) {
    stop(
      "Could not construct the admissible interval for lambda from W."
    )
  }
  
  bound_lower <- 1 / eig_min
  bound_upper <- 1 / eig_max
  
  ## L-BFGS-B requires closed finite bounds. Optimize on a compact
  ## subset lying strictly inside the eigenvalue-based interval.
  lower <- bound_lower + endpoint_margin * max(1, abs(bound_lower))
  
  upper <- bound_upper - endpoint_margin * max(1, abs(bound_upper))
  
  if (!is.finite(lower) ||
      !is.finite(upper) ||
      lower >= upper) {
    stop(
      "Invalid eigenvalue-based spatial parameter interval."
    )
  }
  
  list(
    lower            = as.numeric(lower),
    upper            = as.numeric(upper),
    bound_lower      = as.numeric(bound_lower),
    bound_upper      = as.numeric(bound_upper),
    eig_min          = as.numeric(eig_min),
    eig_max          = as.numeric(eig_max),
    complex_spectrum = any(abs(Im(ev)) > 1e-8),
    endpoint_margin  = endpoint_margin
  )
}

.sbivml_projected_score <- function(par, score, lower, upper, tol = 1e-7) {
  ## Compute the projected score used to assess KKT stationarity under constraints.
  g        <- as.numeric(score)
  names(g) <- names(par)
  for (j in seq_along(par)) {
    at_lower <- is.finite(lower[j]) && par[j] <= lower[j] + tol * max(1, abs(lower[j]))
    at_upper <- is.finite(upper[j]) && par[j] >= upper[j] - tol * max(1, abs(upper[j]))

    ## KKT for maximization:
    ## lower boundary can be optimal when score <= 0;
    ## upper boundary can be optimal when score >= 0.
    if (at_lower && g[j] < 0) g[j] <- 0
    if (at_upper && g[j] > 0) g[j] <- 0
  }
  g
}

.sbivml_boundary_flags <- function(par, lower, upper, tol = 1e-6) {
  ## Flag parameters that lie at or sufficiently close to their optimization bounds.
  out        <- rep(FALSE, length(par))
  names(out) <- names(par)

  for (j in seq_along(par)) {
    lo <- is.finite(lower[j]) && par[j] <= lower[j] + tol * max(1, abs(lower[j]))
    hi <- is.finite(upper[j]) && par[j] >= upper[j] - tol * max(1, abs(upper[j]))
    out[j] <- lo || hi
  }
  out
}

.sbivml_factor_A <- function(A) {
  tryCatch(Matrix::lu(A), error = function(e) NULL)
}

.sbivml_solve_A <- function(A, RHS, factor = NULL) {
  ans <- NULL
  if (!is.null(factor)) {
    ans <- tryCatch(
      Matrix::solve(factor, RHS),
      error = function(e) NULL
    )
  }

  if (is.null(ans)) {
    ans <- tryCatch(
      Matrix::solve(A, RHS),
      error = function(e) NULL
    )
  }
  ans
}

.sbivml_exact_diag_omega <- function(base) {
  ## Compute diag(Omega) exactly as (1 - rho^2) * diag(A^{-1} A^{-T}) without forming Omega.
  B <- if (!is.null(base$B)) {
    base$B
  } else {
    I_n <- if (!is.null(base$pm_cache) && !is.null(base$pm_cache$I)) {
      base$pm_cache$I
    } else {
      Matrix::Diagonal(base$n)
    }
    B0 <- .sbivml_solve_A(base$A, I_n, factor = base$A_factor)
    if (is.null(B0)) NULL else tryCatch(as.matrix(B0), error = function(e) NULL)
  }

  if (is.null(B) || any(!is.finite(B))) return(NULL)
  
  out <- base$vf * rowSums(B * B)
  rm(B)

  if (any(!is.finite(out)) || any(out <= 0)) return(NULL)
  as.numeric(out)
}

.sbivml_chol_upper <- function(Prec, amd = FALSE, check_factor = FALSE) {
  ## Compute a sparse upper-Cholesky factor, optionally using AMD reordering, and return factorization diagnostics.
  S <- Matrix::forceSymmetric(Prec, uplo = "U")
  ch <- tryCatch(Matrix::Cholesky(S, perm = isTRUE(amd), LDL = FALSE, super = FALSE),
                 error = function(e) NULL)
  if (is.null(ch)) return(NULL)

  ex <- tryCatch(Matrix::expand2(ch, LDL = FALSE), error = function(e) NULL)
  if (is.null(ex) || is.null(ex[["L."]])) return(NULL)
  
  U <- Matrix::drop0(ex[["L."]])
  n <- nrow(S)
  perm0 <- tryCatch(as.integer(ch@perm),error = function(e) integer(0))
  perm <- if (length(perm0) == n) {
    perm0 + 1L
  } else {
    seq_len(n)
  }

  if (!.sbivml_valid_perm(perm, n)) {
    stop("Invalid permutation returned by sparse Cholesky.")
  }

  factor_error <- NA_real_

  if (isTRUE(check_factor)) {
    Sperm <- S[perm, perm, drop = FALSE]
    err <- Matrix::crossprod(U) - Sperm
    den <- max(1, as.numeric(Matrix::norm(Sperm, type = "I")))
    factor_error <- as.numeric(Matrix::norm(err, type = "I")) / den
  }

  list(
    U            = U,
    perm         = as.integer(perm),
    nnz_U        = Matrix::nnzero(U),
    factor_error = factor_error
  )
}

.sbivml_make_upper_row_cache <- function(M, require_positive_diag = TRUE) {
  ## Build a row-wise sparse cache of an upper-triangular matrix to avoid repeated row extraction in the ME/RIS recursions.
  n <- nrow(M)
  Ms <- if (inherits(M, "sparseMatrix")) {
    M
  } else {
    Matrix::Matrix(M, sparse = TRUE)
  }

  Ms    <- Matrix::drop0(Matrix::triu(Ms))
  diagv <- as.numeric(Matrix::diag(Ms))
  bad   <- length(diagv) != n || any(!is.finite(diagv))
  if (isTRUE(require_positive_diag)) bad <- bad || any(diagv <= 0)
  if (bad) stop("Invalid upper-triangular diagonal.")
  
  Mc <- methods::as(Ms, "CsparseMatrix")
  ii <- as.integer(Mc@i) + 1L
  jj <- rep.int(seq_len(n), diff(Mc@p))
  xx <- as.numeric(Mc@x)

  keep <- is.finite(xx) & xx != 0 & jj > ii
  ii   <- ii[keep]
  jj   <- jj[keep]
  xx   <- xx[keep]

  if (length(ii)) {
    grp <- split(seq_along(ii), factor(ii, levels = seq_len(n)), drop = FALSE)
    j_by_row <- lapply(grp,
      function(z) {
        if (length(z)) jj[z] else integer(0)
      }
    )

    x_by_row <- lapply(grp,
      function(z) {
        if (length(z)) xx[z] else numeric(0)
      }
    )
  } else {
    j_by_row <- replicate(n, integer(0), simplify = FALSE)
    x_by_row <- replicate(n, numeric(0), simplify = FALSE)
  }

  list(
    diag      = diagv,
    j         = j_by_row,
    x         = x_by_row,
    nnz_total = n + sum(lengths(j_by_row))
  )
}

.sbivml_chol_upper_derivative <- function(dPrec, U) {
  ## Compute dU from dPrec for Prec = U'U, as required by the analytic ME/RIS gradient.
  if (is.null(dPrec)) return(NULL)
  Ut <- Matrix::t(U)
  X <- tryCatch(Matrix::solve(Ut, dPrec), error = function(e) NULL)
  if (is.null(X)) return(NULL)
  
  Y <- tryCatch(Matrix::solve(Ut, Matrix::t(X)), error = function(e) NULL)
  if (is.null(Y)) return(NULL)
  
  M <- Matrix::t(Y)
  M <- 0.5 * (M + Matrix::t(M))
  F <- Matrix::triu(M)
  dM <- as.numeric(Matrix::diag(M))
  dF <- as.numeric(Matrix::diag(F))

  F <- F - Matrix::Diagonal(nrow(U), x = dF) + Matrix::Diagonal(nrow(U), x = 0.5 * dM)
  Matrix::drop0(F %*% U)
}

.sbivml_chol_upper_derivative_list <- function(dPrec_list, U, rho_index = NULL, rho = NULL) {
  ## Compute dU/dtheta for all parameters, using the closed-form derivative dU/drho_raw = rho * U when applicable.
  p <- length(dPrec_list)
  out <- vector("list", p)
  for (k in seq_len(p)) {
    if (!is.null(rho_index) && k == rho_index) {
      if (!is.null(rho) && is.finite(rho) && rho != 0) {
        out[[k]] <- Matrix::drop0(rho * U)
      }
    } else if (!is.null(dPrec_list[[k]])) {
      out[[k]] <- .sbivml_chol_upper_derivative(dPrec_list[[k]], U)
      if (is.null(out[[k]])) return(NULL)
    }
  }
  out
}

.sbivml_make_dU_caches <- function(dU_list, p) {
  ## Build row-wise sparse caches for the nonzero Cholesky-factor derivatives used in the ME/RIS gradient recursions.
  if (length(dU_list) != p) {
    stop(sprintf("Internal derivative-list length mismatch: length(dU_list)=%d, p=%d", length(dU_list), p))
  }
  caches <- vector("list", p)
  active <- integer(0)

  for (k in seq_len(p)) {
    if (!is.null(dU_list[[k]])) {
      caches[[k]] <- .sbivml_make_upper_row_cache(dU_list[[k]], require_positive_diag = FALSE)
      active <- c(active, k)
    }
  }
  list(
    caches = caches,
    active = active
  )
}

.sbivml_me_pm_grad_from_U <- function(lower, upper, dlower, dupper, U, dU_list) {
  ## Evaluate the precision-based Mendell-Elston recursion and its analytic gradient in a single backward pass.
  n <- length(lower)
  p <- ncol(dlower)

  Uc    <- .sbivml_make_upper_row_cache(U)
  dUc   <- .sbivml_make_dU_caches(dU_list, p)
  xhat  <- numeric(n)
  dxhat <- matrix(0, nrow = n, ncol = p)

  grad <- numeric(p)
  logp <- 0

  for (i in n:1) {
    Uii  <- Uc$diag[i]
    js   <- Uc$j[[i]]
    vals <- Uc$x[[i]]
    g    <- if (!length(js))  0  else  sum(vals * xhat[js])
    dg   <- numeric(p)
    if (length(js)) {
      dg <- as.numeric(crossprod(vals, dxhat[js, , drop = FALSE]))
    }

    dUii <- numeric(p)
    for (k in dUc$active) {
      dc      <- dUc$caches[[k]]
      dUii[k] <- dc$diag[i]
      djs     <- dc$j[[i]]
      if (length(djs)) {
        dg[k] <- dg[k] + sum(dc$x[[i]] * xhat[djs])
      }
    }

    if (is.finite(lower[i])) {
      lo <- Uii * lower[i] + g
      dlo <- Uii * dlower[i, ] + lower[i] * dUii + dg
    } else {
      lo <- -Inf
      dlo <- numeric(p)
    }

    if (is.finite(upper[i])) {
      up <- Uii * upper[i] + g
      dup <- Uii * dupper[i, ] + upper[i] * dUii + dg
    } else {
      up <- Inf
      dup <- numeric(p)
    }

    tt <- .sbivml_one_sided_terms(lo, up)

    if (is.null(tt)) {
      return(list(logp = -Inf, grad = rep(NA_real_, p)))
    }

    dbound <- if (identical(tt$finite_side, "upper")) dup else dlo
    
    grad       <- grad + tt$score_coef * dbound
    deta       <- tt$mean_deriv_coef * dbound
    x_i        <- (tt$mean - g) / Uii
    dx_i       <- (deta - dg - x_i * dUii) / Uii
    xhat[i]    <- x_i
    dxhat[i, ] <- dx_i
    logp <- logp + tt$logp
  }

  list(logp = as.numeric(logp), grad = as.numeric(grad))
}

.sbivml_chol_lower_derivative <- function(dSigma, L) {
  ## M = L^{-1} dSigma L^{-T}.  Compute it with triangular solves instead
  ## of explicitly forming L^{-1}; this is algebraically identical but
  ## avoids an inverse and two dense matrix multiplications.
  X <- tryCatch(forwardsolve(L, as.matrix(dSigma)), error = function(e) NULL)
  if (is.null(X)) return(NULL)

  Y <- tryCatch(forwardsolve(L, t(X)), error = function(e) NULL)
  if (is.null(Y)) return(NULL)

  M <- t(Y)
  M <- 0.5 * (M + t(M))
  F <- M
  F[upper.tri(F)] <- 0
  diag(F) <- 0.5 * diag(M)
  L %*% F
}

.sbivml_me_vc_grad <- function(lower, upper, Omega, dlower, dupper, dOmega_list, rho_index = NULL, rho = NULL) {
  ## Evaluate the covariance-based Mendell-Elston recursion and its analytic gradient in a single forward pass.
  n <- length(lower)
  p <- ncol(dlower)
  L <- tryCatch(t(chol(as.matrix(Omega))), error = function(e) NULL)
  if (is.null(L)) return(list(logp = -Inf, grad = rep(NA_real_, p)))
  
  dL <- vector("list", p)
  for (k in seq_len(p)) {
    if (!is.null(rho_index) && k == rho_index) {
      ## dOmega/d rho_raw = -2*rho*Omega => dL/d rho_raw = -rho*L.
      if (!is.null(rho) && is.finite(rho) && rho != 0) dL[[k]] <- -rho * L
    } else if (!is.null(dOmega_list[[k]])) {
      dL[[k]] <- .sbivml_chol_lower_derivative(dOmega_list[[k]], L)
      if (is.null(dL[[k]])) {
        return(list(logp = -Inf, grad = rep(NA_real_, p)))
      }
    }
  }

  active_dL <- which(!vapply(dL, is.null, logical(1)))
  eta       <- numeric(n)
  deta      <- matrix(0, nrow = n, ncol = p)
  grad      <- numeric(p)
  logp      <- 0
  for (i in seq_len(n)) {
    ind <- if (i > 1L) {
      seq_len(i - 1L)
    } else {
      integer(0)
    }

    g <- if (!length(ind)) {
      0
    } else {
      sum(L[i, ind] * eta[ind])
    }

    dg <- numeric(p)
    if (length(ind)) {
      dg <- as.numeric(crossprod(L[i, ind], deta[ind, , drop = FALSE]))
      for (k in active_dL) {
        dg[k] <- dg[k] + sum(dL[[k]][i, ind] * eta[ind])
      }
    }

    Lii  <- L[i, i]
    dLii <- numeric(p)
    for (k in active_dL) dLii[k] <- dL[[k]][i, i]
    lo_num <- lower[i] - g
    up_num <- upper[i] - g
    lo     <- lo_num / Lii
    up     <- up_num / Lii
    tt     <- .sbivml_one_sided_terms(lo, up)

    if (is.null(tt)) return(list(logp = -Inf, grad = rep(NA_real_, p)))
    if (is.finite(lower[i])) {
      dlo <- ((dlower[i, ] - dg) * Lii - lo_num * dLii) / Lii^2
    } else {
      dlo <- numeric(p)
    }

    if (is.finite(upper[i])) {
      dup <- ((dupper[i, ] - dg) * Lii - up_num * dLii) / Lii^2
    } else {
      dup <- numeric(p)
    }

    dbound    <- if (identical(tt$finite_side, "upper")) dup else dlo
    grad      <- grad + tt$score_coef * dbound
    eta[i]    <- tt$mean
    deta[i, ] <- tt$mean_deriv_coef * dbound
    logp      <- logp + tt$logp
  }

  list(logp = as.numeric(logp), grad = as.numeric(grad), L = L)
}

.sbivml_ris_pm_grad_from_U <- function(s, ds, U, dU_list, draws) {
  ## Evaluate the precision-based RIS/GHK simulator and its analytic gradient over all draws in a single backward recursion.
  n      <- length(s)
  R      <- ncol(draws)
  p      <- ncol(ds)
  Uc     <- .sbivml_make_upper_row_cache(U)
  dUc    <- .sbivml_make_dU_caches(dU_list, p)
  zdraw  <- matrix(0, nrow = n, ncol = R)
  dzdraw <- array(0, dim = c(n, R, p))
  logp_r <- rep(0, R)
  grad_r <- matrix(0, nrow = R, ncol = p)

  alive    <- rep(TRUE, R)
  log_xmin <- log(.Machine$double.xmin)
  for (i in n:1) {
    rr <- which(alive)
    if (!length(rr)) break
    Uii  <- Uc$diag[i]
    js   <- Uc$j[[i]]
    vals <- Uc$x[[i]]
    g <- if (!length(js)) {
      rep(0, length(rr))
    } else {
      zsub <- matrix(zdraw[js, rr, drop = FALSE], nrow = length(js), ncol = length(rr))
      as.numeric(crossprod(vals, zsub))
    }
    nu <- as.numeric(Uii * s[i] + g)
    lp <- stats::pnorm(nu, log.p = TRUE)
    bad <- !is.finite(lp)
    if (any(bad)) alive[rr[bad]] <- FALSE
    ok <- which(!bad)
    if (!length(ok)) next

    .sbivml_ok <- rr[ok]
    nu_ok <- nu[ok]
    lp_ok <- lp[ok]

    dg <- matrix(0, nrow = length(.sbivml_ok), ncol = p)
    if (length(js)) {
      zsub <- matrix(zdraw[js, .sbivml_ok, drop = FALSE], nrow = length(js), ncol = length(.sbivml_ok))
      for (k in seq_len(p)) {
        dzsub <- matrix(dzdraw[js, .sbivml_ok, k], nrow = length(js), ncol = length(.sbivml_ok))
        dg[, k] <- as.numeric(crossprod(vals, dzsub))
        if (k %in% dUc$active) {
          dc <- dUc$caches[[k]]
          djs <- dc$j[[i]]

          if (length(djs)) {
            zsub_d <- matrix(zdraw[djs, .sbivml_ok, drop = FALSE], nrow = length(djs), ncol = length(.sbivml_ok))
            dg[, k] <- dg[, k] + as.numeric(crossprod(dc$x[[i]], zsub_d))
          }
        }
      }
    }

    dUii <- numeric(p)
    for (k in dUc$active) dUii[k] <- dUc$caches[[k]]$diag[i]

    dnu <- matrix(0, nrow = length(.sbivml_ok), ncol = p)
    for (k in seq_len(p)) dnu[, k] <- Uii * ds[i, k] + s[i] * dUii[k] + dg[, k]
    

    ratio <- .sbivml_mills_upper(nu_ok)
    grad_r[.sbivml_ok, ] <- grad_r[.sbivml_ok, , drop = FALSE] + ratio * dnu
    logp_r[.sbivml_ok] <- logp_r[.sbivml_ok] + lp_ok
    pcond <- exp(pmax(lp_ok, log_xmin))
    pcond <- pmin(pcond, 1 - .Machine$double.eps)
    eta <- .sbivml_safe_qnorm(draws[i, .sbivml_ok] * pcond)
    active_draw <- lp_ok > log_xmin & pcond < 1 - .Machine$double.eps

    mult <- rep(0, length(.sbivml_ok))

    if (any(active_draw)) {
      phi_nu <- stats::dnorm(nu_ok[active_draw])
      phi_eta <- stats::dnorm(eta[active_draw])
      mult[active_draw] <- draws[i, .sbivml_ok[active_draw]] * phi_nu / pmax(phi_eta, .Machine$double.xmin)
    }

    deta <- dnu * mult
    z_i <-(eta - g[ok]) / Uii
    dz_i <- matrix(0, nrow = length(.sbivml_ok), ncol = p)
    for (k in seq_len(p)) dz_i[, k] <- (deta[, k] - dg[, k] - z_i * dUii[k]) / Uii
    zdraw[i, .sbivml_ok] <- z_i
    for (k in seq_len(p)) dzdraw[i, .sbivml_ok, k] <- dz_i[, k]
  }

  if (any(!alive)) {
    logp_r[!alive] <- -Inf
    grad_r[!alive, ] <- 0
  }

  m <- max(logp_r)
  if (!is.finite(m)) return(list(logp = -Inf, grad = rep(NA_real_, p)))
  w <- exp(logp_r - m)
  w[!is.finite(w)] <- 0
  bad_rows <- !is.finite(logp_r) | !stats::complete.cases(grad_r)
  if (any(bad_rows)) {
    w[bad_rows] <- 0
    grad_r[bad_rows, ] <- 0
  }

  sw <- sum(w)
  if (!is.finite(sw) ||sw <= 0) return(list(logp = -Inf, grad = rep(NA_real_, p)))
  
  list(
    logp = as.numeric(m + log(mean(w))),
    grad = as.numeric(crossprod(w / sw, grad_r))
  )
}

.sbivml_ris_vc_grad <- function(s, ds, Omega, dOmega_list, draws, rho_index = NULL, rho = NULL) {
  ## Evaluate the covariance-based RIS likelihood approximation and its analytic gradient using the GHK recursion.
  n <- length(s)
  R <- ncol(draws)
  p <- ncol(ds)
  L <- tryCatch(t(chol(as.matrix(Omega))), error = function(e) NULL)
  if (is.null(L)) return(list(logp = -Inf, grad = rep(NA_real_, p)))
  
  dL <- vector("list", p)
  for (k in seq_len(p)) {
    if (!is.null(rho_index) && k == rho_index) {
      ## dOmega/d rho_raw = -2*rho*Omega, hence dL/d rho_raw = -rho*L.
      ## Keep this closed-form scale derivative, but use the legacy
      ## parameter-loop recursion below to avoid large 3D block copies in R.
      if (!is.null(rho) && is.finite(rho) && rho != 0) {
        dL[[k]] <- -rho * L
      }
    } else if (!is.null(dOmega_list[[k]])) {
      dL[[k]] <- .sbivml_chol_lower_derivative(dOmega_list[[k]], L)
      if (is.null(dL[[k]])) return(list(logp = -Inf, grad = rep(NA_real_, p)))
    }
  }

  eta      <- matrix(0, nrow = n, ncol = R)
  deta     <- array(0, dim = c(n, R, p))
  logp_r   <- rep(0, R)
  grad_r   <- matrix(0, nrow = R, ncol = p)
  alive    <- rep(TRUE, R)
  log_xmin <- log(.Machine$double.xmin)

  for (i in seq_len(n)) {
    rr <- which(alive)
    if (!length(rr)) break

    ind <- if (i > 1L) seq_len(i - 1L) else integer(0)
    if (!length(ind)) {
      g <- rep(0, length(rr))
    } else {
      eta_sub <- matrix(eta[ind, rr, drop = FALSE], nrow = length(ind), ncol = length(rr))
      g <- as.numeric(crossprod(L[i, ind], eta_sub))
    }

    Lii   <- L[i, i]
    delta <- s[i] - g
    nu    <- delta / Lii
    lp    <- stats::pnorm(nu, log.p = TRUE)
    bad   <- !is.finite(lp)
    if (any(bad)) alive[rr[bad]] <- FALSE
    ok <- which(!bad)
    if (!length(ok)) next

    .sbivml_ok <- rr[ok]
    nu_ok     <- nu[ok]
    delta_ok  <- delta[ok]
    lp_ok     <- lp[ok]

    dg <- matrix(0, nrow = length(.sbivml_ok), ncol = p)

    if (length(ind)) {
      eta_sub <- matrix(
        eta[ind, .sbivml_ok, drop = FALSE],
        nrow = length(ind),
        ncol = length(.sbivml_ok)
      )

      for (k in seq_len(p)) {
        deta_sub <- matrix(
          deta[ind, .sbivml_ok, k],
          nrow = length(ind),
          ncol = length(.sbivml_ok)
        )
        dg[, k] <- as.numeric(crossprod(L[i, ind], deta_sub))
        if (!is.null(dL[[k]])) {
          dg[, k] <- dg[, k] + as.numeric(crossprod(dL[[k]][i, ind], eta_sub))
        }
      }
    }

    dLii <- numeric(p)

    for (k in seq_len(p)) {
      if (!is.null(dL[[k]])) {
        dLii[k] <- dL[[k]][i, i]
      }
    }

    dnu <- matrix(0, nrow = length(.sbivml_ok), ncol = p)
    for (k in seq_len(p)) dnu[, k] <-((ds[i, k] - dg[, k]) * Lii - delta_ok * dLii[k]) / Lii^2
    
    ratio               <- .sbivml_mills_upper(nu_ok)
    grad_r[.sbivml_ok, ] <- grad_r[.sbivml_ok, , drop = FALSE] + ratio * dnu
    logp_r[.sbivml_ok]   <- logp_r[.sbivml_ok] + lp_ok
    pcond               <- exp(pmax(lp_ok, log_xmin))
    pcond               <- pmin(pcond, 1 - .Machine$double.eps)
    eta_i               <- .sbivml_safe_qnorm(draws[i, .sbivml_ok] * pcond)
    eta[i, .sbivml_ok]   <- eta_i
    active_draw         <- lp_ok > log_xmin & pcond < 1 - .Machine$double.eps
    mult                <- rep(0, length(.sbivml_ok))

    if (any(active_draw)) {
      phi_nu <- stats::dnorm(nu_ok[active_draw])
      phi_eta <- stats::dnorm(eta_i[active_draw])
      mult[active_draw] <-draws[i, .sbivml_ok[active_draw]] * phi_nu / pmax(phi_eta, .Machine$double.xmin)
    }

    for (k in seq_len(p)) deta[i, .sbivml_ok, k] <- mult * dnu[, k]
  }

  if (any(!alive)) {
    logp_r[!alive] <- -Inf
    grad_r[!alive, ] <- 0
  }

  m <- max(logp_r)
  if (!is.finite(m)) return(list(logp = -Inf, grad = rep(NA_real_, p)))
  w <- exp(logp_r - m)
  w[!is.finite(w)] <- 0

  bad_rows <- !is.finite(logp_r) | !stats::complete.cases(grad_r)

  if (any(bad_rows)) {
    w[bad_rows] <- 0
    grad_r[bad_rows, ] <- 0
  }

  sw <- sum(w)
  if (!is.finite(sw) || sw <= 0) return(list(logp = -Inf, grad = rep(NA_real_, p)))
  
  list(
    logp = as.numeric(m + log(mean(w))),
    grad = as.numeric(crossprod(w / sw, grad_r))
  )
}

.sbivml_mg_me_order <- function(lower, upper, diagOmega, precision_storage = TRUE) {
  ## Construct the Mendell-Elston ordering from marginal truncation probabilities, reversing it for backward precision recursions.
  sd_i <- sqrt(diagOmega)
  p_i <- stats::pnorm(upper / sd_i) - stats::pnorm(lower / sd_i)
  if (any(!is.finite(p_i))) return(NULL)
  
  ## Covariance recursion is forward: smallest p first.
  ord_forward <- order(p_i, decreasing = FALSE)

  if (isTRUE(precision_storage)) {
    ## Precision recursion processes n:1, so store the reverse.
    return(as.integer(rev(ord_forward)))
  }

  as.integer(ord_forward)
}

.sbivml_mg_ris_order <- function(s, diagOmega, precision_storage = TRUE) {
  ## Construct the RIS ordering from marginal sign probabilities, reversing it for backward precision recursions.
  p_i <- stats::pnorm(s / sqrt(diagOmega))
  if (any(!is.finite(p_i))) return(NULL)
  
  ord_forward <- order(p_i,decreasing = FALSE)
  if (isTRUE(precision_storage)) {
    return(as.integer(rev(ord_forward)))
  }
  as.integer(ord_forward)
}

.sbivml_sign_adjust <- function(M, q) {
  ## Apply the binary-sign transformation Q M Q, with Q = diag(2y - 1), to orient all truncation constraints consistently.
  if (inherits(M, "Matrix")) {
    Q <- Matrix::Diagonal(x = as.numeric(q))
    Matrix::drop0(Q %*% M %*% Q)
  } else {
    M * tcrossprod(q, q)
  }
}

.sbivml_pm_factor <- function(Prec, ord_stat, append_amd = FALSE, check_factor = FALSE) {
  ## Factor the precision matrix after statistical ordering, optionally appending AMD to reduce sparse Cholesky fill-in.
  n <- nrow(Prec)
  if (!.sbivml_valid_perm(ord_stat, n)) return(NULL)

  Pstat <- Prec[ord_stat, ord_stat, drop = FALSE]
  ff    <- .sbivml_chol_upper(Pstat, amd = isTRUE(append_amd), check_factor = check_factor)
  if (is.null(ff)) return(NULL)

  rel <- if (isTRUE(append_amd)) ff$perm else seq_len(n)
  if (!.sbivml_valid_perm(rel, n)) return(NULL)

  ord_final <- as.integer(ord_stat[rel])
  if (!.sbivml_valid_perm(ord_final, n)) return(NULL)

  list(
    U = ff$U,
    ord_stat = as.integer(ord_stat),
    ord_fill_relative = as.integer(rel),
    ord_final = ord_final,
    amd_nontrivial = isTRUE(append_amd) && any(rel != seq_len(n)),
    nnz_U = ff$nnz_U,
    factor_error = ff$factor_error,
    nnz_P_upper = Matrix::nnzero(Matrix::triu(Pstat[rel, rel, drop = FALSE]))
  )
}


